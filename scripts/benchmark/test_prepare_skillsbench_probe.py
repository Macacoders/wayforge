"""Offline checks for the disposable probe's model pin."""

from pathlib import Path
import json
import tempfile
import unittest

import prepare_skillsbench_probe


class PinFreeModelsTests(unittest.TestCase):
    def test_accepts_installer_pinned_models_and_keeps_agent_models(self):
        with tempfile.TemporaryDirectory() as temp:
            path = Path(temp) / "opencode.jsonc"
            path.write_text("// Generated by wayforge bootstrap\n" + json.dumps({
                "default_agent": "planner",
                "model": prepare_skillsbench_probe.FREE_MODEL,
                "small_model": prepare_skillsbench_probe.FREE_MODEL,
                "agent": {"code": {"model": "opencode/big-pickle"}},
            }))
            prepare_skillsbench_probe.pin_free_models(path)
            self.assertTrue(path.read_text().startswith("// Generated by wayforge bootstrap\n"))
            config = json.loads(path.read_text().split("\n", 1)[1])
            self.assertEqual(config["default_agent"], "delivery")
            self.assertEqual(config["model"], prepare_skillsbench_probe.FREE_MODEL)
            self.assertEqual(config["small_model"], prepare_skillsbench_probe.FREE_MODEL)
            self.assertEqual(config["agent"]["code"]["model"], "opencode/big-pickle")

    def test_rejects_unexpected_root_model(self):
        with tempfile.TemporaryDirectory() as temp:
            path = Path(temp) / "opencode.jsonc"
            path.write_text(json.dumps({
                "default_agent": "planner",
                "model": "opencode/paid-model",
                "small_model": "",
            }))
            with self.assertRaisesRegex(RuntimeError, "model"):
                prepare_skillsbench_probe.pin_free_models(path)

    def test_accepts_older_empty_root_and_helper_fields(self):
        with tempfile.TemporaryDirectory() as temp:
            path = Path(temp) / "opencode.jsonc"
            path.write_text(json.dumps({
                "default_agent": "planner",
                "model": "",
                "small_model": "",
            }))
            prepare_skillsbench_probe.pin_free_models(path)
            config = json.loads(path.read_text())
            self.assertEqual(config["default_agent"], "delivery")
            self.assertEqual(config["model"], prepare_skillsbench_probe.FREE_MODEL)
            self.assertEqual(config["small_model"], prepare_skillsbench_probe.FREE_MODEL)


if __name__ == "__main__":
    unittest.main()
