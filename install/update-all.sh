#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
source "$SCRIPT_DIR/lib/managed_sync.sh"

DRY_RUN=0
FORCE=1  # Always force when updating managed trees

MANAGED_OPENCODE_HEADER='// Generated by ai-config bootstrap.sh'
MANAGED_DIR_MARKER='.ai-config-managed'

log() {
  printf '[ai-config] %s\n' "$*"
}

usage() {
  cat <<'EOF'
Usage:
  ./install/update-all.sh [--dry-run]

Options:
  --dry-run      Print planned operations without modifying files.
  -h, --help     Show this help.
EOF
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --dry-run)
      DRY_RUN=1
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      log "error: unknown option: $1"
      usage
      exit 1
      ;;
  esac
done

tracking_file="$ROOT_DIR/installed-projects.md"

if [[ ! -f "$tracking_file" ]]; then
  log "error: tracking file not found: $tracking_file"
  exit 1
fi

# Convert a path from the tracking file to a host-native path.
# Supports Windows paths (C:\...) on both WSL (via wslpath) and Git Bash (via \ → /).
resolve_path() {
  local p="$1"
  # WSL: convert Windows-style paths to WSL paths (/mnt/c/...)
  if command -v wslpath &>/dev/null && [[ "$p" == [A-Za-z]:\\* || "$p" == [A-Za-z]:/* ]]; then
    wslpath -u "$p"
    return
  fi
  # Git Bash / msys2: replace backslashes with forward slashes
  printf '%s' "$p" | sed 's/\\/\//g'
}

updated=0
skipped=0
stale_entries=()

while IFS= read -r line; do
  # Skip comment lines and empty lines
  [[ "$line" =~ ^#.*$ || -z "$line" ]] && continue

  resolved=$(resolve_path "$line")
  if [[ -d "$resolved" ]]; then
    log "updating project: $line"
    sync_managed_tree "$ROOT_DIR/base/opencode/agents" "$resolved/.opencode/agents" 1
    sync_managed_tree "$ROOT_DIR/base/opencode/commands" "$resolved/.opencode/commands" 1
    sync_managed_tree "$ROOT_DIR/base/opencode/skills" "$resolved/.opencode/skills" 1
    updated=$((updated + 1))
  else
    log "warning: project path not found, skipping: $line"
    skipped=$((skipped + 1))
    stale_entries+=("$line")
  fi
done < "$tracking_file"

if [[ ${#stale_entries[@]} -gt 0 && "$DRY_RUN" -eq 0 ]]; then
  echo ""
  read -r -p "Remove stale entries from tracking file? [y/N]: " response || true
  if [[ "$response" == "y" || "$response" == "Y" ]]; then
    grep -vFx -f <(printf '%s\n' "${stale_entries[@]}") "$tracking_file" > "${tracking_file}.tmp" || true
    mv "${tracking_file}.tmp" "$tracking_file"
    log "removed ${#stale_entries[@]} stale entries from tracking file"
  fi
fi

log "update complete: $updated projects updated, $skipped skipped"
