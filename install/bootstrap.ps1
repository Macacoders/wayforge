#!/usr/bin/env pwsh
#Requires -Version 5.1
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$SCRIPT_DIR = Split-Path -Parent $MyInvocation.MyCommand.Path
$ROOT_DIR = Resolve-Path (Join-Path $SCRIPT_DIR '..') | Select-Object -ExpandProperty Path

$DRY_RUN = $false
$FORCE = $false
$REPO_PATH = ''
$PROVIDERS_RAW = 'openai'
$MODEL_OVERRIDE = ''
$SMALL_MODEL_OVERRIDE = ''
$RUNTIME = 'opencode'

$MANAGED_OPENCODE_HEADER = '// Generated by ai-config bootstrap.sh'
$MANAGED_DIR_MARKER = '.ai-config-managed'
$SELECTED_PROVIDERS = @()
$SYNC_MANAGED_TREE_LAST_ACTION = 'skipped'

function Test-Administrator {
    $currentPrincipal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
    return $currentPrincipal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

function log {
    param([string]$Message)
    Write-Host "[ai-config] $Message"
}

function run-mkdir {
    param([string]$Dir)
    if ($DRY_RUN) {
        return
    }
    New-Item -ItemType Directory -Path $Dir -Force | Out-Null
}

function run-rm {
    param([string]$Path)
    if ($DRY_RUN) {
        log "DRY-RUN: Remove-Item -Path $Path"
        return
    }
    if (Test-Path $Path) {
        Remove-Item -Path $Path -Force
    }
}

function run-ln {
    param(
        [string]$Src,
        [string]$Dst
    )
    if ($DRY_RUN) {
        log "DRY-RUN: New-Item -ItemType SymbolicLink -Path $Dst -Target $Src"
        return
    }
    New-Item -ItemType SymbolicLink -Path $Dst -Target $Src | Out-Null
}

function run-copytree {
    param(
        [string]$Src,
        [string]$Dst
    )
    if ($DRY_RUN) {
        log "DRY-RUN: Copy-Item -Path $Src -Destination $Dst -Recurse"
        return
    }
    Copy-Item -Path $Src -Destination $Dst -Recurse
}

function run-rmrf {
    param([string]$Path)
    if ($DRY_RUN) {
        log "DRY-RUN: Remove-Item -Path $Path -Recurse -Force"
        return
    }
    if (Test-Path $Path) {
        Remove-Item -Path $Path -Recurse -Force
    }
}

function run-writefile {
    param(
        [string]$Path,
        [string]$Content
    )
    if ($DRY_RUN) {
        log "DRY-RUN: write file $Path"
        return
    }
    [System.IO.File]::WriteAllText($Path, $Content)
}

function ensure-dir {
    param([string]$Dir)
    if (Test-Path $Dir -PathType Container) {
        return
    }
    if ($DRY_RUN) {
        log "DRY-RUN: New-Item -ItemType Directory -Path $Dir"
        return
    }
    run-mkdir $Dir
    log "created directory: $Dir"
}

function safe-link {
    param(
        [string]$Src,
        [string]$Dst
    )

    if (-not (Test-Path $Src)) {
        log "error: source does not exist: $Src"
        exit 1
    }

    # Check if destination exists and is a symlink
    if (Test-Path $Dst) {
        $item = Get-Item $Dst -ErrorAction SilentlyContinue
        if ($item -and $item.Attributes -match 'ReparsePoint') {
            # It's a symlink/junction
            $currentTarget = $item.Target
            if ($currentTarget -eq $Src -and -not $FORCE) {
                log "kept existing symlink: $Dst -> $Src"
                return
            }

            if ($FORCE) {
                run-rm $Dst
                run-ln $Src $Dst
                if ($DRY_RUN) {
                    log "DRY-RUN: would replace symlink: $Dst -> $Src"
                } else {
                    log "linked (replaced symlink): $Dst -> $Src"
                }
                return
            }

            log "skip existing symlink (use -Force to replace): $Dst -> $currentTarget"
            return
        }

        # It's a regular file or directory
        log "skip existing non-symlink: $Dst"
        return
    }

    $parent = Split-Path -Parent $Dst
    ensure-dir $parent
    run-ln $Src $Dst
    if ($DRY_RUN) {
        log "DRY-RUN: would link: $Dst -> $Src"
    } else {
        log "linked: $Dst -> $Src"
    }
}

function Contains-Provider {
    param([string]$Needle)
    foreach ($provider in $SELECTED_PROVIDERS) {
        if ($provider -eq $Needle) {
            return $true
        }
    }
    return $false
}

function Parse-Providers {
    param([string]$Raw)

    $tokens = $Raw -split ','
    $result = New-Object System.Collections.Generic.List[string]

    foreach ($tokenRaw in $tokens) {
        $token = $tokenRaw.Trim()
        switch ($token) {
            'openai' {
                if (-not $result.Contains('openai')) {
                    $result.Add('openai')
                }
            }
            'laberit' {
                if (-not $result.Contains('laberit')) {
                    $result.Add('laberit')
                }
            }
            default {
                log "error: invalid provider '$token' in -Providers"
                log '       allowed values: openai, laberit, openai,laberit'
                exit 1
            }
        }
    }

    if ($result.Count -eq 0) {
        log 'error: -Providers must include at least one provider'
        exit 1
    }

    $script:SELECTED_PROVIDERS = $result.ToArray()
}

function Validate-ModelOverride {
    param(
        [string]$Value,
        [string]$FlagName
    )

    if ([string]::IsNullOrWhiteSpace($Value)) {
        return
    }

    $parts = $Value.Split('/', 2)
    if ($parts.Count -lt 2 -or [string]::IsNullOrWhiteSpace($parts[0]) -or [string]::IsNullOrWhiteSpace($parts[1])) {
        log "error: $FlagName must be in '<provider>/<model>' format"
        exit 1
    }

    if (-not (Contains-Provider $parts[0])) {
        log "error: $FlagName provider '$($parts[0])' is not enabled by -Providers"
        exit 1
    }
}

function Build-EnabledProvidersJson {
    $quoted = @()
    foreach ($provider in $SELECTED_PROVIDERS) {
        $quoted += ('"{0}"' -f $provider)
    }
    return [string]::Join(', ', $quoted)
}

