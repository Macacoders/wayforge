function Generate-OpenCodeJsoncContent {
    param([string]$Runtime)

    $defaultModel = 'openai/gpt-5.5'
    $defaultSmallModel = 'openai/gpt-5.4-mini-fast'

    if ($SELECTED_PROVIDERS.Count -eq 1 -and $SELECTED_PROVIDERS[0] -eq 'laberit') {
        $defaultModel = 'laberit/laberit-ai-preview'
        $defaultSmallModel = 'laberit/laberit-ai'
    }

    $finalModel = if ([string]::IsNullOrWhiteSpace($MODEL_OVERRIDE)) { $defaultModel } else { $MODEL_OVERRIDE }
    $finalSmallModel = if ([string]::IsNullOrWhiteSpace($SMALL_MODEL_OVERRIDE)) { $defaultSmallModel } else { $SMALL_MODEL_OVERRIDE }

    $schemaUrl = if ($Runtime -eq 'kilocode') { 'https://app.kilo.ai/config.json' } else { 'https://opencode.ai/config.json' }

    $enabledJson = Build-EnabledProvidersJson
    $providerBlock = Build-ProviderBlockJson
    $agentBlock = Build-AgentBlockJson

    return @"
$MANAGED_OPENCODE_HEADER
{
  "`$schema": "$schemaUrl",
  "enabled_providers": [$enabledJson],
  "model": "$finalModel",
  "small_model": "$finalSmallModel",
  "default_agent": "planner",
  "share": "disabled",
  $agentBlock,
  "provider": {
$providerBlock
  },
  "permission": {
    "skill": {
      "*": "allow"
    }
  }
}
"@
}

function Is-ManagedOpenCodeFile {
    param([string]$Path)
    if (-not (Test-Path $Path -PathType Leaf)) {
        return $false
    }

    $firstLine = Get-Content -Path $Path -TotalCount 1 -ErrorAction SilentlyContinue
    return ($firstLine -eq $MANAGED_OPENCODE_HEADER)
}

function Sync-GeneratedOpenCodeJsonc {
    param(
        [string]$Dst,
        [string]$Runtime
    )

    $parent = Split-Path -Parent $Dst
    ensure-dir $parent

    if (Test-Path $Dst -PathType Leaf) {
        $item = Get-Item $Dst -ErrorAction SilentlyContinue
        if ($item -and $item.Attributes -match 'ReparsePoint') {
            if (-not $FORCE) {
                log "skip existing symlink (use -Force to replace): $Dst -> $($item.Target)"
                return
            }
            run-rm $Dst
        } elseif (-not $FORCE) {
            log "skip existing non-symlink: $Dst"
            return
        } elseif (-not (Is-ManagedOpenCodeFile $Dst)) {
            log "skip existing non-managed file (not replacing): $Dst"
            return
        }
    } elseif (Test-Path $Dst) {
        # Existing non-file path (e.g., directory)
        log "skip existing non-symlink: $Dst"
        return
    }

    $content = Generate-OpenCodeJsoncContent -Runtime $Runtime
    run-writefile $Dst $content
    if ($DRY_RUN) {
        log "DRY-RUN: would generate local config: $Dst"
    } else {
        log "generated local config: $Dst"
    }
}

function Is-ManagedDir {
    param([string]$Path)
    return (Test-Path (Join-Path $Path $MANAGED_DIR_MARKER) -PathType Leaf)
}

function Is-ManagedFile {
    param([string]$Path)
    return (Test-Path "${Path}.ai-config-managed" -PathType Leaf)
}

function Sync-ManagedTree {
    param(
        [string]$Src,
        [string]$Dst,
        [bool]$ForceReplaceUnmanaged = $false
    )

    if (-not (Test-Path $Src -PathType Container)) {
        log "error: source directory does not exist: $Src"
        exit 1
    }

    $script:SYNC_MANAGED_TREE_LAST_ACTION = 'skipped'

    if (Test-Path $Dst) {
        $item = Get-Item $Dst -ErrorAction SilentlyContinue
        if ($item -and $item.Attributes -match 'ReparsePoint') {
            if (-not $FORCE) {
                log "skip existing symlink (use -Force to replace): $Dst -> $($item.Target)"
                return
            }
            run-rm $Dst
        } elseif (-not $FORCE) {
            log "skip existing non-symlink: $Dst"
            return
        } elseif (-not ($item.PSIsContainer) -or (-not $ForceReplaceUnmanaged -and -not (Is-ManagedDir $Dst))) {
            log "skip existing non-managed path (not replacing): $Dst"
            return
        } else {
            run-rmrf $Dst
        }
    }

    $parent = Split-Path -Parent $Dst
    ensure-dir $parent
    run-copytree $Src $Dst
    run-writefile (Join-Path $Dst $MANAGED_DIR_MARKER) 'generated-by=ai-config-bootstrap.sh'
    $script:SYNC_MANAGED_TREE_LAST_ACTION = 'copied'
    if ($DRY_RUN) {
        log "DRY-RUN: would copy managed tree: $Dst"
    } else {
        log "copied managed tree: $Dst"
    }
}

function Get-AgentPermissionBlock {
    param(
        [string]$AgentName,
        [string]$PermissionsFile
    )

    $lines = [System.IO.File]::ReadAllLines($PermissionsFile)
    $inAgents = $false
    $agentsIndent = -1
    $capturingAgent = $false
    $targetAgentIndent = -1
    $captured = New-Object System.Collections.Generic.List[string]

    foreach ($line in $lines) {
        if ([string]::IsNullOrWhiteSpace($line)) {
            continue
        }

        $indent = $line.Length - $line.TrimStart(' ').Length
        $trimmed = $line.TrimStart(' ')

        if (-not $inAgents) {
            if ($trimmed -eq 'agents:') {
                $inAgents = $true
                $agentsIndent = $indent
            }
            continue
        }

        if ($indent -le $agentsIndent) {
            break
        }

        if ($indent -eq ($agentsIndent + 2) -and $trimmed -match '^([^:#]+):\s*$') {
            $currentAgent = $matches[1].TrimEnd()
            if ($currentAgent -eq $AgentName) {
                $capturingAgent = $true
                $targetAgentIndent = $indent
            } elseif ($capturingAgent) {
                break
            } else {
                $capturingAgent = $false
            }
            continue
        }

        if (-not $capturingAgent) {
            continue
        }

        if ($indent -le $targetAgentIndent) {
            break
        }

        if ($trimmed.StartsWith('#')) {
            continue
        }

        $captured.Add($line.Substring($targetAgentIndent + 1))
    }

    if ($captured.Count -eq 0) {
        return $null
    }

    return @('permission:') + $captured.ToArray()
}

function Render-AgentWithCentralPermissions {
    param(
        [string]$SrcFile,
        [string]$DstFile,
        [string]$AgentName,
        [string]$PermissionsFile
    )

    $permissionBlockLines = Get-AgentPermissionBlock -AgentName $AgentName -PermissionsFile $PermissionsFile
    if (-not $permissionBlockLines) {
        log "error: missing permissions in $PermissionsFile for agent '$AgentName'"
        exit 1
    }

    if ($DRY_RUN) {
        log "DRY-RUN: would render centralized permissions: $DstFile"
        return
    }

    $srcLines = [System.IO.File]::ReadAllLines($SrcFile)
    $output = New-Object System.Collections.Generic.List[string]
    $inFrontmatter = $false
    $frontmatterDone = $false
    $skippingPermission = $false
    $permissionIndent = -1
    $inserted = $false

    foreach ($line in $srcLines) {
        if ($line -eq '---') {
            if (-not $inFrontmatter) {
                $inFrontmatter = $true
                $output.Add($line)
                continue
            }

            if ($inFrontmatter -and -not $frontmatterDone) {
                if (-not $inserted) {
                    foreach ($permLine in $permissionBlockLines) {
                        $output.Add($permLine)
                    }
                    $inserted = $true
                }
                $frontmatterDone = $true
                $inFrontmatter = $false
                $output.Add($line)
                continue
            }
        }

        if (-not $inFrontmatter -or $frontmatterDone) {
            $output.Add($line)
            continue
        }

        $indent = $line.Length - $line.TrimStart(' ').Length
        $trimmed = $line.TrimStart(' ')

        if ($skippingPermission) {
            if ([string]::IsNullOrWhiteSpace($trimmed) -or $indent -gt $permissionIndent) {
                continue
            }
            $skippingPermission = $false
        }

        if (-not $inserted -and $trimmed -match '^description:\s') {
            $prefix = ' ' * $indent
            foreach ($permLine in $permissionBlockLines) {
                $output.Add("$prefix$permLine")
            }
            $inserted = $true
        }

        if ($trimmed -eq 'permission:') {
            $skippingPermission = $true
            $permissionIndent = $indent
            continue
        }

        $output.Add($line)
    }

    [System.IO.File]::WriteAllLines($DstFile, $output)
}

function Sync-AgentsTreeWithPermissions {
    param(
        [string]$SrcDir,
        [string]$DstDir,
        [string]$PermissionsFile
    )

    Sync-ManagedTree -Src $SrcDir -Dst $DstDir -ForceReplaceUnmanaged $true
    if ($SYNC_MANAGED_TREE_LAST_ACTION -ne 'copied') {
        return
    }

    Get-ChildItem -Path $SrcDir -Filter '*.md' -File | ForEach-Object {
        $agentName = $_.BaseName
        $dstFile = Join-Path $DstDir $_.Name
        Render-AgentWithCentralPermissions -SrcFile $_.FullName -DstFile $dstFile -AgentName $agentName -PermissionsFile $PermissionsFile
    }
}

function Sync-ManagedFile {
    param(
        [string]$Src,
        [string]$Dst
    )

    if (-not (Test-Path $Src -PathType Leaf)) {
        log "error: source file does not exist: $Src"
        exit 1
    }

    if (Test-Path $Dst) {
        $item = Get-Item $Dst -ErrorAction SilentlyContinue
        if ($item -and $item.Attributes -match 'ReparsePoint') {
            if (-not $FORCE) {
                log "skip existing file (use -Force to replace): $Dst"
                return
            }
            run-rm $Dst
        } elseif (-not $FORCE) {
            log "skip existing file (use -Force to replace): $Dst"
            return
        } elseif (-not (Is-ManagedFile $Dst)) {
            log "skip existing unmanaged file (use -Force to replace): $Dst"
            return
        } else {
            run-rm $Dst
        }
    }

    $parent = Split-Path -Parent $Dst
    ensure-dir $parent
    Copy-Item -Path $Src -Destination $Dst
    run-writefile "${Dst}.ai-config-managed" 'generated-by=ai-config-bootstrap.sh'
    if ($DRY_RUN) {
        log "DRY-RUN: would copy managed file: $Dst"
    } else {
        log "copied managed file: $Dst"
    }
}

function install-repo {
    param([string]$Repo)

    if (-not (Test-Path $Repo -PathType Container)) {
        log "error: repo path does not exist: $Repo"
        exit 1
    }

    ensure-dir (Join-Path $Repo '.opencode')

    Parse-Providers $PROVIDERS_RAW
    Validate-ModelOverride $MODEL_OVERRIDE '-Model'
    Validate-ModelOverride $SMALL_MODEL_OVERRIDE '-SmallModel'

    $configFilename = if ($RUNTIME -eq 'kilocode') { 'kilo.jsonc' } else { 'opencode.jsonc' }
    Sync-GeneratedOpenCodeJsonc -Dst (Join-Path $Repo $configFilename) -Runtime $RUNTIME
    Sync-ManagedFile (Join-Path (Join-Path $ROOT_DIR 'templates') 'AGENTS.md') (Join-Path $Repo 'AGENTS.md')
    Sync-ManagedTree (Join-Path (Join-Path $ROOT_DIR 'base') 'opencode/agents') (Join-Path (Join-Path $Repo '.opencode') 'agents') $true
    Sync-ManagedTree (Join-Path (Join-Path $ROOT_DIR 'base') 'opencode/commands') (Join-Path (Join-Path $Repo '.opencode') 'commands') $true
    Sync-ManagedTree (Join-Path (Join-Path $ROOT_DIR 'base') 'opencode/skills') (Join-Path (Join-Path $Repo '.opencode') 'skills') $true

    log "repo bootstrap complete for: $Repo"
}

function usage {
    @'
Usage:
  .\install\bootstrap.ps1 -Repo <path> [-Providers <list>] [-Model <provider/model>] [-SmallModel <provider/model>] [-Runtime <runtime>] [-DryRun] [-Force]

Options:
  -Repo <path>   Install OpenCode config into a target project.
  -Providers     Provider set: openai | laberit | openai,laberit (default: openai)
  -Model         Override default model (must belong to an enabled provider)
  -SmallModel    Override default small model (must belong to an enabled provider)
  -Runtime       Runtime to configure: opencode (default) or kilocode.
  -DryRun        Print planned operations without modifying files.
  -Force         Replace generated OpenCode runtime trees and managed targets/symlinks.
  -h, -Help      Show this help.
'@ | Write-Host
}

# Parse arguments
for ($i = 0; $i -lt $args.Count; $i++) {
    switch ($args[$i]) {
        '-Repo' {
            $i++
            if ($i -lt $args.Count) {
                $REPO_PATH = $args[$i]
            } else {
                log "error: -Repo requires a path"
                exit 1
            }
        }
        '-DryRun' {
            $DRY_RUN = $true
        }
        '-Providers' {
            $i++
            if ($i -lt $args.Count) {
                $PROVIDERS_RAW = $args[$i]
            } else {
                log 'error: -Providers requires a value'
                exit 1
            }
        }
        '-Model' {
            $i++
            if ($i -lt $args.Count) {
                $MODEL_OVERRIDE = $args[$i]
            } else {
                log 'error: -Model requires a value'
                exit 1
            }
        }
        '-SmallModel' {
            $i++
            if ($i -lt $args.Count) {
                $SMALL_MODEL_OVERRIDE = $args[$i]
            } else {
                log 'error: -SmallModel requires a value'
                exit 1
            }
        }
        '-Runtime' {
            $i++
            if ($i -lt $args.Count) {
                $RUNTIME = $args[$i]
            } else {
                log 'error: -Runtime requires a value'
                exit 1
            }
        }
        '-Force' {
            $FORCE = $true
        }
        { $_ -in '-h', '-Help', '--help' } {
            usage
            exit 0
        }
        default {
            log "error: unknown option: $($args[$i])"
            usage
            exit 1
        }
    }
}

# Validate runtime
if ($RUNTIME -ne 'opencode' -and $RUNTIME -ne 'kilocode') {
    log "error: invalid -Runtime '$RUNTIME'. Allowed values: opencode, kilocode"
    exit 1
}

if ([string]::IsNullOrEmpty($REPO_PATH)) {
    log "error: -Repo <path> is required"
    usage
    exit 1
}

# Resolve full path
$REPO_PATH = Resolve-Path $REPO_PATH -ErrorAction SilentlyContinue | Select-Object -ExpandProperty Path
if (-not $REPO_PATH) {
    log "error: cannot resolve repo path"
    exit 1
}

# Check for administrator privileges (required for creating symlinks on Windows)
if (-not $DRY_RUN -and -not (Test-Administrator)) {
    log "warning: Administrator privileges are required to create symbolic links on Windows."
    log "         Please run PowerShell as Administrator, or enable Developer Mode."
    log "         Falling back to dry-run mode. Use -DryRun to suppress this warning."
    $DRY_RUN = $true
}

install-repo $REPO_PATH
log "done"
