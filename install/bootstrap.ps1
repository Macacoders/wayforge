function Track-InstalledProject {
    param([string]$RepoPath)

    if ($DRY_RUN) { return }
    if ($FORCE) { return }

    $trackingFile = Join-Path $ROOT_DIR 'installed-projects.json'

    # Resolve canonical absolute path
    $canonical = Resolve-Path -LiteralPath $RepoPath -ErrorAction SilentlyContinue | Select-Object -ExpandProperty Path
    if (-not $canonical) {
        $canonical = (Get-Item $RepoPath).FullName
    }

    $name = Split-Path $canonical -Leaf
    $timestamp = (Get-Date).ToUniversalTime().ToString('yyyy-MM-ddTHH:mm:ssZ')

    if (-not (Test-Path $trackingFile -PathType Leaf)) {
        # Create tracking file with envelope and initial project entry
        $entry = @{
            name        = $name
            path        = $canonical
            description = $null
            lastUpdated = $timestamp
        }
        $data = @{
            version  = 1
            projects = @($entry)
        }
        $data | ConvertTo-Json -Depth 3 | Set-Content -Path $trackingFile
        log "tracked installed project: $canonical"
        return
    }

    # Read existing file
    try {
        $data = Get-Content -Path $trackingFile -Raw -ErrorAction Stop | ConvertFrom-Json -ErrorAction Stop
    } catch {
        log "warning: failed to parse tracking file, skipping: $_"
        return
    }

    # Ensure projects array exists
    if (-not $data.projects) {
        $data.projects = @()
    }

    # Check for duplicate by path
    foreach ($project in $data.projects) {
        if ($project.path -eq $canonical) {
            return
        }
    }

    # Append new entry
    $entry = @{
        name        = $name
        path        = $canonical
        description = $null
        lastUpdated = $timestamp
    }
    $data.projects += $entry

    # Write back
    $data | ConvertTo-Json -Depth 3 | Set-Content -Path $trackingFile
    log "tracked installed project: $canonical"
}

function Test-Administrator {
    $currentPrincipal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
    return $currentPrincipal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

function log {
    param([string]$Message)
    Write-Host "[ai-config] $Message"
}

function safe-link {
    param(
        [string]$Src,
        [string]$Dst
    )

    if (-not (Test-Path $Src)) {
        log "error: source does not exist: $Src"
        exit 1
    }

    # Check if destination exists and is a symlink
    if (Test-Path $Dst) {
        $item = Get-Item $Dst -ErrorAction SilentlyContinue
        if ($item -and $item.Attributes -match 'ReparsePoint') {
            # It's a symlink/junction
            $currentTarget = $item.Target
            if ($currentTarget -eq $Src -and -not $FORCE) {
                log "kept existing symlink: $Dst -> $Src"
                return
            }

            if ($FORCE) {
                run-rm $Dst
                run-ln $Src $Dst
                if ($DRY_RUN) {
                    log "DRY-RUN: would replace symlink: $Dst -> $Src"
                } else {
                    log "linked (replaced symlink): $Dst -> $Src"
                }
                return
            }

            log "skip existing symlink (use -Force to replace): $Dst -> $currentTarget"
            return
        }

        # It's a regular file or directory
        log "skip existing non-symlink: $Dst"
        return
    }

    $parent = Split-Path -Parent $Dst
    ensure-dir $parent
    run-ln $Src $Dst
    if ($DRY_RUN) {
        log "DRY-RUN: would link: $Dst -> $Src"
    } else {
        log "linked: $Dst -> $Src"
    }
}

function Contains-Provider {
    param([string]$Needle)
    foreach ($provider in $SELECTED_PROVIDERS) {
        if ($provider -eq $Needle) {
            return $true
        }
    }
    return $false
}

function Parse-Providers {
    param([string]$Raw)

    $tokens = $Raw -split ','
    $result = New-Object System.Collections.Generic.List[string]

    foreach ($tokenRaw in $tokens) {
        $token = $tokenRaw.Trim()
        switch ($token) {
            'openai' {
                if (-not $result.Contains('openai')) {
                    $result.Add('openai')
                }
            }
            'github-copilot' {
                if (-not $result.Contains('github-copilot')) {
                    $result.Add('github-copilot')
                }
            }
            'laberit' {
                if (-not $result.Contains('laberit')) {
                    $result.Add('laberit')
                }
            }
            default {
                log "error: invalid provider '$token' in -Providers"
                log '       allowed values: openai, github-copilot, laberit, or comma-separated combinations'
                exit 1
            }
        }
    }

    if ($result.Count -eq 0) {
        log 'error: -Providers must include at least one provider'
        exit 1
    }

    $script:SELECTED_PROVIDERS = $result.ToArray()
}

function Validate-ModelOverride {
    param(
        [string]$Value,
        [string]$FlagName
    )

    if ([string]::IsNullOrWhiteSpace($Value)) {
        return
    }

    $parts = $Value.Split('/', 2)
    if ($parts.Count -lt 2 -or [string]::IsNullOrWhiteSpace($parts[0]) -or [string]::IsNullOrWhiteSpace($parts[1])) {
        log "error: $FlagName must be in '<provider>/<model>' format"
        exit 1
    }

    if (-not (Contains-Provider $parts[0])) {
        log "error: $FlagName provider '$($parts[0])' is not enabled by -Providers"
        exit 1
    }
}

function Validate-AgentPreset {
    param([string]$Value)

    if ([string]::IsNullOrWhiteSpace($Value)) {
        return
    }

    switch ($Value) {
        'balanced' { }
        'fast' { }
        'thorough' { }
        default {
            log "error: invalid -AgentPreset '$Value'. Allowed values: balanced, fast, thorough"
            exit 1
        }
    }
}

