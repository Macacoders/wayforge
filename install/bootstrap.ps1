function Build-AgentBlockJsonFromPreset {
    param([string]$Preset)

    $plannerModel = Pick-PlannerModel
    $researchModel = Pick-ResearchModel
    $codeModel = Pick-CodeModel
    $taskanalystModel = Pick-TaskanalystModel

    $plannerSteps = 0
    $researchSteps = 0
    $codeSteps = 0
    $quickcodeSteps = 0
    $testSteps = 0
    $taskanalystSteps = 0
    $reasoningEffort = ''
    $textVerbosity = ''

    switch ($Preset) {
        'fast' {
            $plannerSteps = 12; $researchSteps = 8; $codeSteps = 6
            $quickcodeSteps = 5; $testSteps = 8; $taskanalystSteps = 8
            $reasoningEffort = 'low'; $textVerbosity = 'low'
        }
        'thorough' {
            $plannerSteps = 40; $researchSteps = 24; $codeSteps = 18
            $quickcodeSteps = 12; $testSteps = 24; $taskanalystSteps = 16
            $reasoningEffort = 'medium'; $textVerbosity = 'medium'
        }
        default {
            log "error: unsupported agent preset '$Preset'"
            exit 1
        }
    }

    # Helper function to conditionally build options block
    $getOptionsBlock = {
        param($Model, $Reasoning, $Verbosity)
        if ($Model -match '^openai/' -or $Model -match '^github-copilot/') {
            return ",`n      `"options`": {`n        `"reasoningEffort`": `"$Reasoning`",`n        `"textVerbosity`": `"$Verbosity`"`n      }"
        }
        return ''
    }

    $plannerOptions = & $getOptionsBlock $plannerModel $reasoningEffort $textVerbosity
    $researchOptions = & $getOptionsBlock $researchModel $reasoningEffort $textVerbosity
    $codeOptions = & $getOptionsBlock $codeModel $reasoningEffort $textVerbosity
    $quickcodeOptions = & $getOptionsBlock $codeModel $reasoningEffort $textVerbosity
    $testOptions = & $getOptionsBlock $researchModel $reasoningEffort $textVerbosity
    $taskanalystOptions = & $getOptionsBlock $taskanalystModel $reasoningEffort $textVerbosity

    return Render-AgentPresetTemplate -PlannerModel $plannerModel -ResearchModel $researchModel -CodeModel $codeModel -TaskanalystModel $taskanalystModel -PlannerSteps $plannerSteps -ResearchSteps $researchSteps -CodeSteps $codeSteps -QuickcodeSteps $quickcodeSteps -TestSteps $testSteps -TaskanalystSteps $taskanalystSteps -PlannerOptions $plannerOptions -ResearchOptions $researchOptions -CodeOptions $codeOptions -QuickcodeOptions $quickcodeOptions -TestOptions $testOptions -TaskanalystOptions $taskanalystOptions
}

function Build-EnabledProvidersJson {
    $quoted = @()
    foreach ($provider in $SELECTED_PROVIDERS) {
        $quoted += ('"{0}"' -f $provider)
    }
    return [string]::Join(', ', $quoted)
}

function Read-ProviderBlockFragment {
    param([string]$FileName)

    $providerFragmentDir = Join-Path $ROOT_DIR 'base/opencode/config/providers'
    $fragmentPath = Join-Path $providerFragmentDir $FileName
    if (-not (Test-Path -LiteralPath $fragmentPath -PathType Leaf)) {
        log "error: missing provider config fragment: $fragmentPath"
        exit 1
    }

    $content = Get-Content -LiteralPath $fragmentPath -Raw
    return ($content -replace '(\r?\n)+$','')
}

function Build-ProviderBlockJson {
    $blocks = New-Object System.Collections.Generic.List[string]

    if (Contains-Provider 'openai') {
        $blocks.Add((Read-ProviderBlockFragment 'openai-provider-block.jsonc'))
    }

    if (Contains-Provider 'github-copilot') {
        $blocks.Add((Read-ProviderBlockFragment 'github-copilot-provider-block.jsonc'))
    }

    if (Contains-Provider 'laberit') {
        $blocks.Add((Read-ProviderBlockFragment 'laberit-provider-block.jsonc'))
    }

    return [string]::Join(",`n", $blocks)
}

function Read-AgentBlockFragment {
    param([string]$FileName)

    $agentFragmentDir = Join-Path $ROOT_DIR 'base/opencode/config/agents'
    $fragmentPath = Join-Path $agentFragmentDir $FileName
    if (-not (Test-Path -LiteralPath $fragmentPath -PathType Leaf)) {
        log "error: missing agent config fragment: $fragmentPath"
        exit 1
    }

    $content = Get-Content -LiteralPath $fragmentPath -Raw
    return ($content -replace '(\r?\n)+$','')
}

function Render-AgentPresetTemplate {
    param(
        [string]$PlannerModel,
        [string]$ResearchModel,
        [string]$CodeModel,
        [string]$TaskanalystModel,
        [int]$PlannerSteps,
        [int]$ResearchSteps,
        [int]$CodeSteps,
        [int]$QuickcodeSteps,
        [int]$TestSteps,
        [int]$TaskanalystSteps,
        [string]$PlannerOptions,
        [string]$ResearchOptions,
        [string]$CodeOptions,
        [string]$QuickcodeOptions,
        [string]$TestOptions,
        [string]$TaskanalystOptions
    )

    $template = Read-AgentBlockFragment 'agent-preset-template.jsonc'
    $replacements = @{
        '{{PLANNER_MODEL}}' = $PlannerModel
        '{{RESEARCH_MODEL}}' = $ResearchModel
        '{{CODE_MODEL}}' = $CodeModel
        '{{TASKANALYST_MODEL}}' = $TaskanalystModel
        '{{PLANNER_STEPS}}' = [string]$PlannerSteps
        '{{RESEARCH_STEPS}}' = [string]$ResearchSteps
        '{{CODE_STEPS}}' = [string]$CodeSteps
        '{{QUICKCODE_STEPS}}' = [string]$QuickcodeSteps
        '{{TEST_STEPS}}' = [string]$TestSteps
        '{{TASKANALYST_STEPS}}' = [string]$TaskanalystSteps
        '{{PLANNER_OPTIONS}}' = $PlannerOptions
        '{{RESEARCH_OPTIONS}}' = $ResearchOptions
        '{{CODE_OPTIONS}}' = $CodeOptions
        '{{QUICKCODE_OPTIONS}}' = $QuickcodeOptions
        '{{TEST_OPTIONS}}' = $TestOptions
        '{{TASKANALYST_OPTIONS}}' = $TaskanalystOptions
    }

    foreach ($key in $replacements.Keys) {
        $template = $template.Replace($key, $replacements[$key])
    }

    return $template
}

function Build-AgentBlockJson {
    if ($AGENT_PRESET -and $AGENT_PRESET -ne 'balanced') {
        return Build-AgentBlockJsonFromPreset $AGENT_PRESET
    }

    if ((Contains-Provider 'openai') -and (Contains-Provider 'github-copilot')) {
        return Read-AgentBlockFragment 'balanced-openai-github-copilot-agent-block.jsonc'
    }

    if ($SELECTED_PROVIDERS.Count -eq 1 -and $SELECTED_PROVIDERS[0] -eq 'github-copilot') {
        return Read-AgentBlockFragment 'balanced-github-copilot-only-agent-block.jsonc'
    }

    if ($SELECTED_PROVIDERS.Count -eq 1 -and $SELECTED_PROVIDERS[0] -eq 'laberit') {
        return Read-AgentBlockFragment 'balanced-laberit-only-agent-block.jsonc'
    }

    return Read-AgentBlockFragment 'balanced-default-agent-block.jsonc'
}

function Generate-OpenCodeJsoncContent {
    param([string]$Runtime)

    $defaultModel = 'openai/gpt-5.5'
    $defaultSmallModel = 'openai/gpt-5.4-mini'

    if ($SELECTED_PROVIDERS.Count -eq 1 -and $SELECTED_PROVIDERS[0] -eq 'github-copilot') {
        $defaultModel = 'github-copilot/gpt-5.4'
        $defaultSmallModel = 'github-copilot/gpt-5.3-codex'
    }

    if ($SELECTED_PROVIDERS.Count -eq 1 -and $SELECTED_PROVIDERS[0] -eq 'laberit') {
        $defaultModel = 'laberit/laberit-ai-preview'
        $defaultSmallModel = 'laberit/laberit-ai'
    }

    if ((Contains-Provider 'openai') -and (Contains-Provider 'github-copilot')) {
        $defaultModel = 'openai/gpt-5.5'
        $defaultSmallModel = 'github-copilot/gemini-3.5-flash'
    }

    $finalModel = if ([string]::IsNullOrWhiteSpace($MODEL_OVERRIDE)) { $defaultModel } else { $MODEL_OVERRIDE }
    $finalSmallModel = if ([string]::IsNullOrWhiteSpace($SMALL_MODEL_OVERRIDE)) { $defaultSmallModel } else { $SMALL_MODEL_OVERRIDE }

    $schemaUrl = if ($Runtime -eq 'kilocode') { 'https://app.kilo.ai/config.json' } else { 'https://opencode.ai/config.json' }

    $enabledJson = Build-EnabledProvidersJson
    $providerBlock = Build-ProviderBlockJson
    $agentBlock = Build-AgentBlockJson

    return @"
$MANAGED_OPENCODE_HEADER
{
  "`$schema": "$schemaUrl",
  "enabled_providers": [$enabledJson],
  "model": "$finalModel",
  "small_model": "$finalSmallModel",
  "default_agent": "planner",
  "share": "disabled",
  $agentBlock,
  "provider": {
$providerBlock
  },
  "permission": {
    "skill": {
      "*": "allow"
    }
  }
}
"@
}

function Sync-GeneratedOpenCodeJsonc {
    param(
        [string]$Dst,
        [string]$Runtime
    )

    $parent = Split-Path -Parent $Dst
    ensure-dir $parent

    if (Test-Path $Dst -PathType Leaf) {
        $item = Get-Item $Dst -ErrorAction SilentlyContinue
        if ($item -and $item.Attributes -match 'ReparsePoint') {
            if (-not $FORCE) {
                log "skip existing symlink (use -Force to replace): $Dst -> $($item.Target)"
                return
            }
            run-rm $Dst
        } elseif (-not $FORCE) {
            log "skip existing non-symlink: $Dst"
            return
        } elseif (-not (Is-ManagedOpenCodeFile $Dst)) {
            log "skip existing non-managed file (not replacing): $Dst"
            return
        }
    } elseif (Test-Path $Dst) {
        # Existing non-file path (e.g., directory)
        log "skip existing non-symlink: $Dst"
        return
    }

    $content = Generate-OpenCodeJsoncContent -Runtime $Runtime
    run-writefile $Dst $content
    if ($DRY_RUN) {
        log "DRY-RUN: would generate local config: $Dst"
    } else {
        log "generated local config: $Dst"
    }
}


function install-repo {
    param([string]$Repo)

    if (-not (Test-Path $Repo -PathType Container)) {
        log "error: repo path does not exist: $Repo"
        exit 1
    }

    ensure-dir (Join-Path $Repo '.opencode')

    Parse-Providers $PROVIDERS_RAW
    Validate-ModelOverride $MODEL_OVERRIDE '-Model'
    Validate-ModelOverride $SMALL_MODEL_OVERRIDE '-SmallModel'
    Validate-AgentPreset $AGENT_PRESET

    $configFilename = if ($RUNTIME -eq 'kilocode') { 'kilo.jsonc' } else { 'opencode.jsonc' }
    Sync-GeneratedOpenCodeJsonc -Dst (Join-Path $Repo $configFilename) -Runtime $RUNTIME
    Sync-ManagedFile (Join-Path (Join-Path $ROOT_DIR 'templates') 'AGENTS.md') (Join-Path $Repo 'AGENTS.md')
    Sync-ManagedTree (Join-Path (Join-Path $ROOT_DIR 'base') 'opencode/agents') (Join-Path (Join-Path $Repo '.opencode') 'agents') $true
    Sync-ManagedTree (Join-Path (Join-Path $ROOT_DIR 'base') 'opencode/commands') (Join-Path (Join-Path $Repo '.opencode') 'commands') $true
    Sync-ManagedTree (Join-Path (Join-Path $ROOT_DIR 'base') 'opencode/skills') (Join-Path (Join-Path $Repo '.opencode') 'skills') $true

    Track-InstalledProject $Repo

    log "repo bootstrap complete for: $Repo"
}

function usage {
    @'
Usage:
  .\install\bootstrap.ps1 -Repo <path> [-Providers <list>] [-Model <provider/model>] [-SmallModel <provider/model>] [-Runtime <runtime>] [-AgentPreset <name>] [-DryRun] [-Force]

Options:
  -Repo <path>     Install OpenCode config into a target project.
  -Providers       Provider set: openai | github-copilot | laberit | comma-separated combinations (default: openai)
  -Model           Override default model (must belong to an enabled provider)
  -SmallModel      Override default small model (must belong to an enabled provider)
  -Runtime         Runtime to configure: opencode (default) or kilocode.
  -AgentPreset     Optional agent profile: balanced | fast | thorough (default: balanced behavior)
  -DryRun          Print planned operations without modifying files.
  -Force           Refresh managed targets and generated runtime trees; preserve unmanaged local files.
  -h, -Help        Show this help.
'@ | Write-Host
}

# Parse arguments
for ($i = 0; $i -lt $args.Count; $i++) {
    switch ($args[$i]) {
        '-Repo' {
            $i++
            if ($i -lt $args.Count) {
                $REPO_PATH = $args[$i]
            } else {
                log "error: -Repo requires a path"
                exit 1
            }
        }
        '-DryRun' {
            $DRY_RUN = $true
        }
        '-Providers' {
            $i++
            if ($i -lt $args.Count) {
                $PROVIDERS_RAW = $args[$i]
            } else {
                log 'error: -Providers requires a value'
                exit 1
            }
        }
        '-Model' {
            $i++
            if ($i -lt $args.Count) {
                $MODEL_OVERRIDE = $args[$i]
            } else {
                log 'error: -Model requires a value'
                exit 1
            }
        }
        '-SmallModel' {
            $i++
            if ($i -lt $args.Count) {
                $SMALL_MODEL_OVERRIDE = $args[$i]
            } else {
                log 'error: -SmallModel requires a value'
                exit 1
            }
        }
        '-Runtime' {
            $i++
            if ($i -lt $args.Count) {
                $RUNTIME = $args[$i]
            } else {
                log 'error: -Runtime requires a value'
                exit 1
            }
        }
        '-Force' {
            $FORCE = $true
        }
        '-AgentPreset' {
            $i++
            if ($i -lt $args.Count) {
                $AGENT_PRESET = $args[$i]
            } else {
                log 'error: -AgentPreset requires a value'
                exit 1
            }
        }
        { $_ -in '-h', '-Help', '--help' } {
            usage
            exit 0
        }
        default {
            log "error: unknown option: $($args[$i])"
            usage
            exit 1
        }
    }
}

# Validate runtime
if ($RUNTIME -ne 'opencode' -and $RUNTIME -ne 'kilocode') {
    log "error: invalid -Runtime '$RUNTIME'. Allowed values: opencode, kilocode"
    exit 1
}

if ([string]::IsNullOrEmpty($REPO_PATH)) {
    log "error: -Repo <path> is required"
    usage
    exit 1
}

# Resolve full path
$REPO_PATH = Resolve-Path $REPO_PATH -ErrorAction SilentlyContinue | Select-Object -ExpandProperty Path
if (-not $REPO_PATH) {
    log "error: cannot resolve repo path"
    exit 1
}

install-repo $REPO_PATH
log "done"
