#!/usr/bin/env pwsh
#Requires -Version 5.1
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$SCRIPT_DIR = Split-Path -Parent $MyInvocation.MyCommand.Path
$ROOT_DIR = Resolve-Path (Join-Path $SCRIPT_DIR '..') | Select-Object -ExpandProperty Path
. (Join-Path $SCRIPT_DIR 'lib/managed_sync.ps1')

$DRY_RUN = $false
$FORCE = $true  # Always force when updating managed trees

$MANAGED_OPENCODE_HEADER = '// Generated by ai-config bootstrap.sh'
$MANAGED_DIR_MARKER = '.ai-config-managed'

function log {
    param([string]$Message)
    Write-Host "[ai-config] $Message"
}

function usage {
    @'
Usage:
  .\install\update-all.ps1 [-DryRun] [-Help]

Options:
  -DryRun          Print planned operations without modifying files.
  -h, -Help        Show this help.
'@ | Write-Host
}

# Parse arguments
for ($i = 0; $i -lt $args.Count; $i++) {
    switch ($args[$i]) {
        '-DryRun' {
            $DRY_RUN = $true
        }
        { $_ -in '-h', '-Help', '--help' } {
            usage
            exit 0
        }
        default {
            log "error: unknown option: $($args[$i])"
            usage
            exit 1
        }
    }
}

$trackingFile = Join-Path $ROOT_DIR 'installed-projects.md'

if (-not (Test-Path $trackingFile -PathType Leaf)) {
    log "error: tracking file not found: $trackingFile"
    exit 1
}

$updated = 0
$skipped = 0
$staleEntries = New-Object System.Collections.ArrayList

$lines = Get-Content $trackingFile

foreach ($line in $lines) {
    # Skip comment lines and empty lines
    if ([string]::IsNullOrWhiteSpace($line) -or $line.TrimStart().StartsWith('#')) {
        continue
    }

    $path = $line.Trim()
    if ([string]::IsNullOrEmpty($path)) {
        continue
    }

    if (Test-Path $path -PathType Container) {
        log "updating project: $path"
        Sync-ManagedTree (Join-Path $ROOT_DIR 'base/opencode/agents') (Join-Path $path '.opencode/agents') $true
        Sync-ManagedTree (Join-Path $ROOT_DIR 'base/opencode/commands') (Join-Path $path '.opencode/commands') $true
        Sync-ManagedTree (Join-Path $ROOT_DIR 'base/opencode/skills') (Join-Path $path '.opencode/skills') $true
        $updated++
    } else {
        log "warning: project path not found, skipping: $path"
        $skipped++
        $null = $staleEntries.Add($path)
    }
}

if ($staleEntries.Count -gt 0 -and -not $DRY_RUN) {
    Write-Host ''
    $response = Read-Host "Remove stale entries from tracking file? [y/N]"
    if ($response.Trim().ToLower() -eq 'y') {
        $content = Get-Content $trackingFile | Where-Object { $_ -notin $staleEntries }
        $content | Set-Content $trackingFile
        log "removed $($staleEntries.Count) stale entries from tracking file"
    }
}

log "update complete: $updated projects updated, $skipped skipped"
