log() {
	printf '[ai-config] %s\n' "$*"
}

safe_link() {
	local src="$1"
	local dst="$2"

	if [[ ! -e "$src" ]]; then
		log "error: source does not exist: $src"
		exit 1
	fi

	if [[ -L "$dst" ]]; then
		local current
		current="$(readlink "$dst")"
		if [[ "$current" == "$src" && "$FORCE" -eq 0 ]]; then
			log "kept existing symlink: $dst -> $src"
			return
		fi

		if [[ "$FORCE" -eq 1 ]]; then
			run_rm "$dst"
			run_ln "$src" "$dst"
			if [[ "$DRY_RUN" -eq 1 ]]; then
				log "DRY-RUN: would replace symlink: $dst -> $src"
			else
				log "linked (replaced symlink): $dst -> $src"
			fi
			return
		fi

		log "skip existing symlink (use --force to replace): $dst -> $current"
		return
	fi

	if [[ -e "$dst" ]]; then
		log "skip existing non-symlink: $dst"
		return
	fi

	local parent
	parent="$(dirname "$dst")"
	ensure_dir "$parent"
	run_ln "$src" "$dst"
	if [[ "$DRY_RUN" -eq 1 ]]; then
		log "DRY-RUN: would link: $dst -> $src"
	else
		log "linked: $dst -> $src"
	fi
}

contains_provider() {
	local needle="$1"
	local item
	for item in "${SELECTED_PROVIDERS[@]}"; do
		if [[ "$item" == "$needle" ]]; then
			return 0
		fi
	done
	return 1
}

has_real_provider() {
	local p
	for p in "${SELECTED_PROVIDERS[@]}"; do
		if [[ "$p" != "free-tier" ]]; then
			return 0
		fi
	done
	return 1
}

validate_free_tier_runtime() {
	if contains_provider "free-tier" && [[ "$RUNTIME" != "opencode" ]]; then
		log "error: free-tier provider is only available for opencode runtime"
		exit 1
	fi
}

parse_providers() {
	local raw="$1"
	local token
	local seen_openai=0
	local seen_github_copilot=0
	local seen_laberit=0
	local seen_opencode_go=0
	local seen_free_tier=0

	IFS=',' read -r -a _providers_in <<<"$raw"
	SELECTED_PROVIDERS=()

	for token in "${_providers_in[@]}"; do
		case "$token" in
		openai)
			if [[ "$seen_openai" -eq 0 ]]; then
				SELECTED_PROVIDERS+=("openai")
				seen_openai=1
			fi
			;;
		github-copilot)
			if [[ "$seen_github_copilot" -eq 0 ]]; then
				SELECTED_PROVIDERS+=("github-copilot")
				seen_github_copilot=1
			fi
			;;
		laberit)
			if [[ "$seen_laberit" -eq 0 ]]; then
				SELECTED_PROVIDERS+=("laberit")
				seen_laberit=1
			fi
			;;
		opencode-go)
			if [[ "$seen_opencode_go" -eq 0 ]]; then
				SELECTED_PROVIDERS+=("opencode-go")
				seen_opencode_go=1
			fi
			;;
		free-tier)
			if [[ "$seen_free_tier" -eq 0 ]]; then
				SELECTED_PROVIDERS+=("free-tier")
				seen_free_tier=1
			fi
			;;
		*)
			log "error: invalid provider '$token' in --providers"
			log "       allowed values: openai, github-copilot, laberit, opencode-go, free-tier, or comma-separated combinations"
			exit 1
			;;
		esac
	done

	if [[ "${#SELECTED_PROVIDERS[@]}" -eq 0 ]]; then
		log "error: --providers must include at least one provider"
		exit 1
	fi
}

validate_model_override() {
	local value="$1"
	local flag_name="$2"
	if [[ -z "$value" ]]; then
		return
	fi

	local provider="${value%%/*}"
	if [[ "$provider" == "$value" ]]; then
		log "error: $flag_name must be in '<provider>/<model>' format"
		exit 1
	fi

	if ! contains_provider "$provider"; then
		log "error: $flag_name provider '$provider' is not enabled by --providers"
		exit 1
	fi
}

validate_agent_preset() {
	local value="$1"
	if [[ -z "$value" ]]; then
		return
	fi

	case "$value" in
	balanced | fast | thorough) ;;

	*)
		log "error: invalid --agent-preset '$value'. Allowed values: balanced, fast, thorough"
		exit 1
		;;
	esac
}

track_installed_project() {
	local path="$1"
	[[ "$DRY_RUN" -eq 1 ]] && return
	[[ "$FORCE" -eq 1 ]] && return

	local tracking_file="$ROOT_DIR/installed-projects.json"
	local canonical name timestamp escaped_path

	canonical=$(realpath "$path" 2>/dev/null || (cd "$path" && pwd -P))

	# Convert to Windows-native format for cross-platform compatibility
	if command -v wslpath &>/dev/null; then
		canonical=$(wslpath -w "$canonical" 2>/dev/null || printf '%s' "$canonical")
	fi

	name=$(basename "$canonical")
	timestamp=$(TZ='Europe/Berlin' date +'%Y-%m-%dT%H:%M:%S%z' | sed 's/\(..\)$/:\1/')
	local install_ref="${INSTALL_REF:-develop}"

	# Escape backslashes for JSON string values (e.g. C:\path → C:\\path)
	escaped_path=$(printf '%s' "$canonical" | sed 's/\\/\\\\/g')

	if [[ ! -f "$tracking_file" ]]; then
		# Create tracking file with envelope and initial project entry
		{
			printf '{\n'
			printf '  "schemaVersion": "1.0.0",\n'
			printf '  "projects": [\n'
			printf '    {\n'
			printf '      "name": "%s",\n' "$name"
			printf '      "path": "%s",\n' "$escaped_path"
			printf '      "lastUpdated": "%s",\n' "$timestamp"
			printf '      "aiConfigVersion": "%s",\n' "$AI_CONFIG_VERSION"
			printf '      "installRef": "%s"\n' "$install_ref"
			printf '    }\n'
			printf '  ]\n'
			printf '}\n'
		} >"$tracking_file"
		log "tracked installed project: $canonical"
		return 0
	fi

	# Duplicate check: exact path match in existing entries
	if grep -Fq '"path": "'"$escaped_path"'"' "$tracking_file" 2>/dev/null; then
		return 0
	fi

	# Append new entry — read file, drop closing "  ]" and "}", insert new entry
	local tmpfile="${tracking_file}.tmp"
	local lines=()

	while IFS= read -r line; do
		lines+=("$line")
	done <"$tracking_file"

	local total=${#lines[@]}

	# Write all lines except the last three (last entry's "}", "  ]", "}")
	for ((i = 0; i < total - 3; i++)); do
		printf '%s\n' "${lines[$i]}" >>"$tmpfile"
	done

	if ((total > 5)); then
		# Existing entries present: turn the previous "    }" into "    },"
		printf '    },\n' >>"$tmpfile"
	else
		# No entries yet: write the "  "projects": [" header line
		printf '%s\n' "${lines[$total - 3]}" >>"$tmpfile"
	fi

	# Write the new project entry
	{
		printf '    {\n'
		printf '      "name": "%s",\n' "$name"
		printf '      "path": "%s",\n' "$escaped_path"
		printf '      "lastUpdated": "%s",\n' "$timestamp"
		printf '      "aiConfigVersion": "%s",\n' "$AI_CONFIG_VERSION"
		printf '      "installRef": "%s"\n' "$install_ref"
		printf '    }\n'
	} >>"$tmpfile"

	# Close the JSON structure
	{
		printf '  ]\n'
		printf '}\n'
	} >>"$tmpfile"

	mv "$tmpfile" "$tracking_file"
	log "tracked installed project: $canonical"
}

