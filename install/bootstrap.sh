#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"

DRY_RUN=0
FORCE=0
REPO_PATH=""
PROVIDERS_RAW="openai"
MODEL_OVERRIDE=""
SMALL_MODEL_OVERRIDE=""

MANAGED_OPENCODE_HEADER='// Generated by ai-config bootstrap.sh'
MANAGED_DIR_MARKER='.ai-config-managed'

log() {
  printf '[ai-config] %s\n' "$*"
}

run_mkdir() {
  local dir="$1"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    return
  fi
  mkdir -p "$dir"
}

run_rm() {
  local path="$1"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    log "DRY-RUN: rm -f $path"
    return
  fi
  rm -f "$path"
}

run_ln() {
  local src="$1"
  local dst="$2"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    log "DRY-RUN: ln -s $src $dst"
    return
  fi
  ln -s "$src" "$dst"
}

run_cp_a() {
  local src="$1"
  local dst="$2"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    log "DRY-RUN: cp -a $src $dst"
    return
  fi
  cp -a "$src" "$dst"
}

run_cp() {
  local src="$1"
  local dst="$2"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    log "DRY-RUN: cp $src $dst"
    return
  fi
  cp "$src" "$dst"
}

run_rm_rf() {
  local path="$1"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    log "DRY-RUN: rm -rf $path"
    return
  fi
  rm -rf "$path"
}

run_write_file() {
  local path="$1"
  local content="$2"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    log "DRY-RUN: write file $path"
    return
  fi
  printf '%s\n' "$content" >"$path"
}

ensure_dir() {
  local dir="$1"
  if [[ -d "$dir" ]]; then
    return
  fi
  if [[ "$DRY_RUN" -eq 1 ]]; then
    log "DRY-RUN: mkdir -p $dir"
    return
  fi
  run_mkdir "$dir"
  log "created directory: $dir"
}

safe_link() {
  local src="$1"
  local dst="$2"

  if [[ ! -e "$src" ]]; then
    log "error: source does not exist: $src"
    exit 1
  fi

  if [[ -L "$dst" ]]; then
    local current
    current="$(readlink "$dst")"
    if [[ "$current" == "$src" && "$FORCE" -eq 0 ]]; then
      log "kept existing symlink: $dst -> $src"
      return
    fi

    if [[ "$FORCE" -eq 1 ]]; then
      run_rm "$dst"
      run_ln "$src" "$dst"
      if [[ "$DRY_RUN" -eq 1 ]]; then
        log "DRY-RUN: would replace symlink: $dst -> $src"
      else
        log "linked (replaced symlink): $dst -> $src"
      fi
      return
    fi

    log "skip existing symlink (use --force to replace): $dst -> $current"
    return
  fi

  if [[ -e "$dst" ]]; then
    log "skip existing non-symlink: $dst"
    return
  fi

  local parent
  parent="$(dirname "$dst")"
  ensure_dir "$parent"
  run_ln "$src" "$dst"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    log "DRY-RUN: would link: $dst -> $src"
  else
    log "linked: $dst -> $src"
  fi
}

contains_provider() {
  local needle="$1"
  local item
  for item in "${SELECTED_PROVIDERS[@]}"; do
    if [[ "$item" == "$needle" ]]; then
      return 0
    fi
  done
  return 1
}

parse_providers() {
  local raw="$1"
  local token
  local seen_openai=0
  local seen_kimi25=0

  IFS=',' read -r -a _providers_in <<<"$raw"
  SELECTED_PROVIDERS=()

  for token in "${_providers_in[@]}"; do
    case "$token" in
      openai)
        if [[ "$seen_openai" -eq 0 ]]; then
          SELECTED_PROVIDERS+=("openai")
          seen_openai=1
        fi
        ;;
      kimi25)
        if [[ "$seen_kimi25" -eq 0 ]]; then
          SELECTED_PROVIDERS+=("kimi25")
          seen_kimi25=1
        fi
        ;;
      *)
        log "error: invalid provider '$token' in --providers"
        log "       allowed values: openai, kimi25, openai,kimi25"
        exit 1
        ;;
    esac
  done

  if [[ "${#SELECTED_PROVIDERS[@]}" -eq 0 ]]; then
    log "error: --providers must include at least one provider"
    exit 1
  fi
}

validate_model_override() {
  local value="$1"
  local flag_name="$2"
  if [[ -z "$value" ]]; then
    return
  fi

  local provider="${value%%/*}"
  if [[ "$provider" == "$value" ]]; then
    log "error: $flag_name must be in '<provider>/<model>' format"
    exit 1
  fi

  if ! contains_provider "$provider"; then
    log "error: $flag_name provider '$provider' is not enabled by --providers"
    exit 1
  fi
}

build_enabled_providers_json() {
  local out=""
  local first=1
  local provider
  for provider in "${SELECTED_PROVIDERS[@]}"; do
    if [[ "$first" -eq 1 ]]; then
      out="\"$provider\""
      first=0
    else
      out="$out, \"$provider\""
    fi
  done
  printf '%s' "$out"
}

build_provider_block_json() {
  local out=""
  if contains_provider "openai"; then
    out='    "openai": {
      "models": {
        "gpt-5.5": {
          "options": {
            "reasoningEffort": "medium",
            "textVerbosity": "medium"
          }
        },
        "gpt-5.5-fast": {
          "options": {
            "reasoningEffort": "medium",
            "textVerbosity": "medium"
          }
        }
      }
    }'
  fi

  if contains_provider "kimi25"; then
    local kimi_block='    "kimi25": {
      "npm": "@ai-sdk/openai-compatible",
      "name": "Kimi 2.5 Azure",
      "options": {
        "baseURL": "{env:KIMI_BASE_URL}",
        "apiKey": "{env:KIMI_API_KEY}",
        "headers": {
          "api-key": "{env:KIMI_API_KEY}",
          "Content-Type": "application/json"
        },
        "queryParams": {
          "api-version": "{env:KIMI_API_VERSION}"
        }
      },
      "models": {
        "Kimi-K2.5": {
          "name": "Kimi K2.5"
        }
      }
    }'

    if [[ -n "$out" ]]; then
      out="$out,
$kimi_block"
    else
      out="$kimi_block"
    fi
  fi

  printf '%s' "$out"
}

build_agent_block_json() {
  if [[ "${#SELECTED_PROVIDERS[@]}" -eq 1 && "${SELECTED_PROVIDERS[0]}" == "kimi25" ]]; then
    cat <<'EOF'
"agent": {
    "planner": {
      "model": "kimi25/Kimi-K2.5"
    },
    "research": {
      "model": "kimi25/Kimi-K2.5"
    },
    "code": {
      "model": "kimi25/Kimi-K2.5"
    },
    "quickcode": {
      "model": "kimi25/Kimi-K2.5"
    },
    "test": {
      "model": "kimi25/Kimi-K2.5"
    },
    "taskanalyst": {
      "model": "kimi25/Kimi-K2.5"
    }
  }
EOF
    return
  fi

  cat <<'EOF'
"agent": {
    "planner": {
      "model": "openai/gpt-5.5"
    },
    "research": {
      "model": "openai/gpt-5.5-fast"
    },
    "code": {
      "model": "openai/gpt-5.3-codex"
    },
    "quickcode": {
      "model": "openai/gpt-5.3-codex"
    },
    "test": {
      "model": "openai/gpt-5.5-fast"
    },
    "taskanalyst": {
      "model": "openai/gpt-5.5-fast"
    }
  }
EOF
}

generate_opencode_jsonc_content() {
  local default_model="openai/gpt-5.5"
  local default_small_model="openai/gpt-5.4-mini-fast"

  if [[ "${#SELECTED_PROVIDERS[@]}" -eq 1 && "${SELECTED_PROVIDERS[0]}" == "kimi25" ]]; then
    default_model="kimi25/Kimi-K2.5"
    default_small_model="kimi25/Kimi-K2.5"
  fi

  local final_model="$default_model"
  local final_small_model="$default_small_model"
  if [[ -n "$MODEL_OVERRIDE" ]]; then
    final_model="$MODEL_OVERRIDE"
  fi
  if [[ -n "$SMALL_MODEL_OVERRIDE" ]]; then
    final_small_model="$SMALL_MODEL_OVERRIDE"
  fi

  local enabled_json
  enabled_json="$(build_enabled_providers_json)"
  local provider_block
  provider_block="$(build_provider_block_json)"
  local agent_block
  agent_block="$(build_agent_block_json)"

  cat <<EOF
$MANAGED_OPENCODE_HEADER
{
  "\$schema": "https://opencode.ai/config.json",
  "enabled_providers": [$enabled_json],
  "model": "$final_model",
  "small_model": "$final_small_model",
  "default_agent": "planner",
  "share": "disabled",
  $agent_block,
  "provider": {
$provider_block
  },
  "permission": {
    "skill": {
      "*": "allow"
    }
  }
}
EOF
}

is_managed_opencode_file() {
  local path="$1"
  if [[ ! -f "$path" ]]; then
    return 1
  fi
  local first_line
  IFS= read -r first_line <"$path" || true
  [[ "$first_line" == "$MANAGED_OPENCODE_HEADER" ]]
}

sync_generated_opencode_jsonc() {
  local dst="$1"
  local parent
  parent="$(dirname "$dst")"
  ensure_dir "$parent"

  if [[ -L "$dst" ]]; then
    if [[ "$FORCE" -ne 1 ]]; then
      log "skip existing symlink (use --force to replace): $dst -> $(readlink "$dst")"
      return
    fi
    run_rm "$dst"
  elif [[ -e "$dst" ]]; then
    if [[ "$FORCE" -ne 1 ]]; then
      log "skip existing non-symlink: $dst"
      return
    fi
    if ! is_managed_opencode_file "$dst"; then
      log "skip existing non-managed file (not replacing): $dst"
      return
    fi
  fi

  local content
  content="$(generate_opencode_jsonc_content)"
  run_write_file "$dst" "$content"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    log "DRY-RUN: would generate local config: $dst"
  else
    log "generated local config: $dst"
  fi
}

is_managed_dir() {
  local path="$1"
  [[ -f "$path/$MANAGED_DIR_MARKER" ]]
}

is_managed_file() {
  local path="$1"
  [[ -f "${path}.ai-config-managed" ]]
}

sync_managed_tree() {
  local src="$1"
  local dst="$2"
  local force_replace_unmanaged="${3:-0}"
  local parent
  parent="$(dirname "$dst")"

  if [[ ! -d "$src" ]]; then
    log "error: source directory does not exist: $src"
    exit 1
  fi

  if [[ -L "$dst" ]]; then
    if [[ "$FORCE" -ne 1 ]]; then
      log "skip existing symlink (use --force to replace): $dst -> $(readlink "$dst")"
      return
    fi
    run_rm "$dst"
  elif [[ -e "$dst" ]]; then
    if [[ "$FORCE" -ne 1 ]]; then
      log "skip existing non-symlink: $dst"
      return
    fi
    if [[ ! -d "$dst" ]] || { [[ "$force_replace_unmanaged" -ne 1 ]] && ! is_managed_dir "$dst"; }; then
      log "skip existing non-managed path (not replacing): $dst"
      return
    fi
    run_rm_rf "$dst"
  fi

  ensure_dir "$parent"
  run_cp_a "$src" "$dst"
  run_write_file "$dst/$MANAGED_DIR_MARKER" "generated-by=ai-config-bootstrap.sh"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    log "DRY-RUN: would copy managed tree: $dst"
  else
    log "copied managed tree: $dst"
  fi
}

sync_managed_file() {
  local src="$1"
  local dst="$2"
  local parent
  parent="$(dirname "$dst")"

  if [[ ! -f "$src" ]]; then
    log "error: source file does not exist: $src"
    exit 1
  fi

  if [[ -L "$dst" ]]; then
    if [[ "$FORCE" -ne 1 ]]; then
      log "skip existing file (use --force to replace): $dst"
      return
    fi
    run_rm "$dst"
  elif [[ -e "$dst" ]]; then
    if [[ "$FORCE" -ne 1 ]]; then
      log "skip existing file (use --force to replace): $dst"
      return
    fi
    if ! is_managed_file "$dst"; then
      log "skip existing unmanaged file (use --force to replace): $dst"
      return
    fi
    run_rm "$dst"
  fi

  ensure_dir "$parent"
  run_cp "$src" "$dst"
  run_write_file "${dst}.ai-config-managed" "generated-by=ai-config-bootstrap.sh"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    log "DRY-RUN: would copy managed file: $dst"
  else
    log "copied managed file: $dst"
  fi
}

install_repo() {
  local repo="$1"

  if [[ ! -d "$repo" ]]; then
    log "error: repo path does not exist: $repo"
    exit 1
  fi

  ensure_dir "$repo/.opencode"

  parse_providers "$PROVIDERS_RAW"
  validate_model_override "$MODEL_OVERRIDE" "--model"
  validate_model_override "$SMALL_MODEL_OVERRIDE" "--small-model"

  sync_generated_opencode_jsonc "$repo/opencode.jsonc"
  sync_managed_file "$ROOT_DIR/templates/AGENTS.md" "$repo/AGENTS.md"
  sync_managed_tree "$ROOT_DIR/base/opencode/agents" "$repo/.opencode/agents" 1
  sync_managed_tree "$ROOT_DIR/base/opencode/commands" "$repo/.opencode/commands" 1
  sync_managed_tree "$ROOT_DIR/base/opencode/skills" "$repo/.opencode/skills" 1

  log "repo bootstrap complete for: $repo"
}

usage() {
  cat <<'EOF'
Usage:
  ./install/bootstrap.sh --repo <path> [--providers <list>] [--model <provider/model>] [--small-model <provider/model>] [--dry-run] [--force]

Options:
  --repo <path>  Link OpenCode config into a target project.
  --providers    Provider set to enable: openai | kimi25 | openai,kimi25 (default: openai)
  --model        Override default model (must belong to an enabled provider)
  --small-model  Override default small model (must belong to an enabled provider)
  --dry-run      Print planned operations without modifying files.
  --force        Replace generated OpenCode runtime trees and managed targets/symlinks.
  -h, --help     Show this help.
EOF
}

if [[ $# -eq 0 ]]; then
  usage
  exit 1
fi

while [[ $# -gt 0 ]]; do
  case "$1" in
    --repo)
      REPO_PATH="${2:-}"
      if [[ -z "$REPO_PATH" ]]; then
        log "error: --repo requires a path"
        exit 1
      fi
      shift 2
      ;;
    --dry-run)
      DRY_RUN=1
      shift
      ;;
    --providers)
      PROVIDERS_RAW="${2:-}"
      if [[ -z "$PROVIDERS_RAW" ]]; then
        log "error: --providers requires a value"
        exit 1
      fi
      shift 2
      ;;
    --model)
      MODEL_OVERRIDE="${2:-}"
      if [[ -z "$MODEL_OVERRIDE" ]]; then
        log "error: --model requires a value"
        exit 1
      fi
      shift 2
      ;;
    --small-model)
      SMALL_MODEL_OVERRIDE="${2:-}"
      if [[ -z "$SMALL_MODEL_OVERRIDE" ]]; then
        log "error: --small-model requires a value"
        exit 1
      fi
      shift 2
      ;;
    --force)
      FORCE=1
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      log "error: unknown option: $1"
      usage
      exit 1
      ;;
  esac
done

if [[ -z "$REPO_PATH" ]]; then
  log "error: --repo <path> is required"
  exit 1
fi

install_repo "$REPO_PATH"
log "done"
