build_agent_block_json_from_preset() {
	local preset="$1"
	local planner_model
	local research_model
	local code_model
	local taskanalyst_model

	planner_model="$(pick_planner_model)"
	research_model="$(pick_research_model)"
	code_model="$(pick_code_model)"
	taskanalyst_model="$(pick_taskanalyst_model)"

	local planner_steps
	local research_steps
	local code_steps
	local quickcode_steps
	local test_steps
	local taskanalyst_steps
	local reasoning_effort
	local text_verbosity

	case "$preset" in
	fast)
		planner_steps=12
		research_steps=8
		code_steps=6
		quickcode_steps=5
		test_steps=8
		taskanalyst_steps=8
		reasoning_effort="low"
		text_verbosity="low"
		;;
	thorough)
		planner_steps=40
		research_steps=24
		code_steps=18
		quickcode_steps=12
		test_steps=24
		taskanalyst_steps=16
		reasoning_effort="medium"
		text_verbosity="medium"
		;;
	*)
		log "error: unsupported agent preset '$preset'"
		exit 1
		;;
	esac

	local planner_options=""
	local research_options=""
	local code_options=""
	local quickcode_options=""
	local test_options=""
	local taskanalyst_options=""

	if [[ "$planner_model" == openai/* || "$planner_model" == github-copilot/* ]]; then
		planner_options=",
      \"options\": {
        \"reasoningEffort\": \"$reasoning_effort\",
        \"textVerbosity\": \"$text_verbosity\"
      }"
	fi

	if [[ "$research_model" == openai/* || "$research_model" == github-copilot/* ]]; then
		research_options=",
      \"options\": {
        \"reasoningEffort\": \"$reasoning_effort\",
        \"textVerbosity\": \"$text_verbosity\"
      }"
	fi

	if [[ "$code_model" == openai/* || "$code_model" == github-copilot/* ]]; then
		code_options=",
      \"options\": {
        \"reasoningEffort\": \"$reasoning_effort\",
        \"textVerbosity\": \"$text_verbosity\"
      }"
		quickcode_options=",
      \"options\": {
        \"reasoningEffort\": \"$reasoning_effort\",
        \"textVerbosity\": \"$text_verbosity\"
      }"
	fi

	if [[ "$research_model" == openai/* || "$research_model" == github-copilot/* ]]; then
		test_options=",
      \"options\": {
        \"reasoningEffort\": \"$reasoning_effort\",
        \"textVerbosity\": \"$text_verbosity\"
      }"
	fi

	if [[ "$taskanalyst_model" == openai/* || "$taskanalyst_model" == github-copilot/* ]]; then
		taskanalyst_options=",
      \"options\": {
        \"reasoningEffort\": \"$reasoning_effort\",
        \"textVerbosity\": \"$text_verbosity\"
      }"
	fi

	render_agent_preset_template \
		"$planner_model" \
		"$research_model" \
		"$code_model" \
		"$taskanalyst_model" \
		"$planner_steps" \
		"$research_steps" \
		"$code_steps" \
		"$quickcode_steps" \
		"$test_steps" \
		"$taskanalyst_steps" \
		"$planner_options" \
		"$research_options" \
		"$code_options" \
		"$quickcode_options" \
		"$test_options" \
		"$taskanalyst_options"
}

build_enabled_providers_json() {
	local out=""
	local first=1

	if [[ "$RUNTIME" == "opencode" ]]; then
		out="\"opencode\""
		first=0
	fi

	local provider
	for provider in "${SELECTED_PROVIDERS[@]}"; do
		# free-tier is an installer-only concept, not a real OpenCode provider
		[[ "$provider" == "free-tier" ]] && continue
		if [[ "$first" -eq 1 ]]; then
			out="\"$provider\""
			first=0
		else
			out="$out, \"$provider\""
		fi
	done
	printf '%s' "$out"
}

build_provider_block_json() {
	local provider_fragment_dir="$SOURCE_DIR/base/opencode/config/providers"
	read_fragment() {
		local name="$1"
		local file="$provider_fragment_dir/$name"
		if [[ ! -f "$file" ]]; then
			log "error: missing provider config fragment: $file"
			exit 1
		fi
		printf '%s' "$(<"$file")"
	}

	local out=""

	if [[ "$RUNTIME" == "opencode" ]]; then
		out="$(read_fragment 'opencode-provider-block.jsonc')"
	fi

	if contains_provider "openai"; then
		local openai_block
		openai_block="$(read_fragment 'openai-provider-block.jsonc')"

		if [[ -n "$out" ]]; then
			out="$out,
$openai_block"
		else
			out="$openai_block"
		fi
	fi

	if contains_provider "github-copilot"; then
		local copilot_block
		copilot_block="$(read_fragment 'github-copilot-provider-block.jsonc')"

		if [[ -n "$out" ]]; then
			out="$out,
$copilot_block"
		else
			out="$copilot_block"
		fi
	fi

	if contains_provider "laberit"; then
		local laberit_block
		laberit_block="$(read_fragment 'laberit-provider-block.jsonc')"

		if [[ -n "$out" ]]; then
			out="$out,
$laberit_block"
		else
			out="$laberit_block"
		fi
	fi

	if contains_provider "opencode-go"; then
		local opencode_go_block
		opencode_go_block="$(read_fragment 'opencode-go-provider-block.jsonc')"

		if [[ -n "$out" ]]; then
			out="$out,
$opencode_go_block"
		else
			out="$opencode_go_block"
		fi
	fi

	printf '%s' "$out"
}

read_agent_fragment() {
	local file="$SOURCE_DIR/base/opencode/config/agents/$1"
	if [[ ! -f "$file" ]]; then
		log "error: missing agent config fragment: $file"
		exit 1
	fi
	printf '%s' "$(<"$file")"
}

