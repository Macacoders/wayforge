build_agent_block_json() {
	if [[ -n "$AGENT_PRESET" && "$AGENT_PRESET" != "balanced" ]]; then
		build_agent_block_json_from_preset "$AGENT_PRESET"
		return
	fi

	if contains_provider "openai" && contains_provider "github-copilot"; then
		read_agent_fragment 'balanced-openai-github-copilot-agent-block.jsonc'
		return
	fi

	if [[ "${#SELECTED_PROVIDERS[@]}" -eq 1 && "${SELECTED_PROVIDERS[0]}" == "github-copilot" ]]; then
		read_agent_fragment 'balanced-github-copilot-only-agent-block.jsonc'
		return
	fi

	if [[ "${#SELECTED_PROVIDERS[@]}" -eq 1 && "${SELECTED_PROVIDERS[0]}" == "laberit" ]]; then
		read_agent_fragment 'balanced-laberit-only-agent-block.jsonc'
		return
	fi

	if [[ "${#SELECTED_PROVIDERS[@]}" -eq 1 && "${SELECTED_PROVIDERS[0]}" == "opencode-go" ]]; then
		read_agent_fragment 'balanced-opencode-go-only-agent-block.jsonc'
		return
	fi

	if ! has_real_provider; then
		return
	fi

	read_agent_fragment 'balanced-openai-only-agent-block.jsonc'
}

generate_opencode_jsonc_content() {
	local runtime="${1:-opencode}"
	local default_model="openai/gpt-5.5"
	local default_small_model="openai/gpt-5.4-mini"

	if [[ "${#SELECTED_PROVIDERS[@]}" -eq 1 && "${SELECTED_PROVIDERS[0]}" == "github-copilot" ]]; then
		default_model="github-copilot/gpt-5.4"
		default_small_model="github-copilot/gpt-5.3-codex"
	fi

	if contains_provider "openai" && contains_provider "github-copilot"; then
		default_model="openai/gpt-5.5"
		default_small_model="github-copilot/gemini-3.5-flash"
	fi

	if [[ "${#SELECTED_PROVIDERS[@]}" -eq 1 && "${SELECTED_PROVIDERS[0]}" == "laberit" ]]; then
		default_model="laberit/laberit-ai-preview"
		default_small_model="laberit/laberit-ai"
	fi

	if [[ "${#SELECTED_PROVIDERS[@]}" -eq 1 && "${SELECTED_PROVIDERS[0]}" == "opencode-go" ]]; then
		default_model="opencode-go/deepseek-v4-pro"
		default_small_model="opencode-go/deepseek-v4-flash"
	fi

	if ! has_real_provider; then
		default_model=""
		default_small_model=""
	fi

	local final_model="$default_model"
	local final_small_model="$default_small_model"
	if [[ -n "$MODEL_OVERRIDE" ]]; then
		final_model="$MODEL_OVERRIDE"
	fi
	if [[ -n "$SMALL_MODEL_OVERRIDE" ]]; then
		final_small_model="$SMALL_MODEL_OVERRIDE"
	fi

	local schema_url="https://opencode.ai/config.json"
	if [[ "$runtime" == "kilocode" ]]; then
		schema_url="https://app.kilo.ai/config.json"
	fi

	local enabled_json
	enabled_json="$(build_enabled_providers_json)"
	local provider_block
	provider_block="$(build_provider_block_json)"
	local agent_block
	agent_block="$(build_agent_block_json)"
	local agent_section=""
	if [[ -n "$agent_block" ]]; then
		agent_section="${agent_block},
  "
	fi

	cat <<EOF
$MANAGED_OPENCODE_HEADER
{
  "\$schema": "$schema_url",
  "enabled_providers": [$enabled_json],
  "model": "$final_model",
  "small_model": "$final_small_model",
  "default_agent": "planner",
  "share": "disabled",
  $agent_section"provider": {
$provider_block
  },
  "permission": {
    "skill": {
      "*": "allow"
    }
  }
}
EOF
}

sync_generated_opencode_jsonc() {
	local repo="$1"
	local runtime="$2"
	local config_file="opencode.jsonc"
	if [[ "$runtime" == "kilocode" ]]; then
		config_file="kilo.jsonc"
	fi
	local dst="$repo/$config_file"
	local parent
	parent="$(dirname "$dst")"
	ensure_dir "$parent"

	if [[ -L "$dst" ]]; then
		if [[ "$FORCE" -ne 1 ]]; then
			log "skip existing symlink (use --force to replace): $dst -> $(readlink "$dst")"
			return
		fi
		run_rm "$dst"
	elif [[ -e "$dst" ]]; then
		if [[ "$FORCE" -ne 1 ]]; then
			log "skip existing non-symlink (use --force to regenerate): $dst"
			return
		fi
		# FORCE=1: regenerate regardless of managed status (fresh-install behavior)
	fi

	local content
	content="$(generate_opencode_jsonc_content "$runtime")"
	run_write_file "$dst" "$content"
	if [[ "$DRY_RUN" -eq 1 ]]; then
		log "DRY-RUN: would generate local config: $dst"
	else
		log "generated local config: $dst"
	fi
}

install_repo() {
	local repo="$1"

	if [[ ! -d "$repo" ]]; then
		log "error: repo path does not exist: $repo"
		exit 1
	fi

	ensure_dir "$repo/.opencode"

	parse_providers "$PROVIDERS_RAW"
	validate_free_tier_runtime
	validate_model_override "$MODEL_OVERRIDE" "--model"
	validate_model_override "$SMALL_MODEL_OVERRIDE" "--small-model"
	validate_agent_preset "$AGENT_PRESET"

	init_managed_manifest "$repo" "$AI_CONFIG_VERSION" "$INSTALL_REF"

	# --- Manifest-aware selective refresh ---
	if [[ -f "$repo/.ai-config-managed" ]]; then
		log "existing install detected, refreshing managed paths from manifest"

		# Allow refresh even without --force (files are known managed)
		local _saved_force="$FORCE"
		FORCE=1

		if read_managed_manifest "$repo"; then
			# Regenerate runtime config only with --force (fresh-install behavior)
			local config_file="opencode.jsonc"
			[[ "$RUNTIME" == "kilocode" ]] && config_file="kilo.jsonc"
			if [[ "$_saved_force" = "1" ]]; then
				sync_generated_opencode_jsonc "$repo" "$RUNTIME"
			else
				log "kept existing $config_file (use --force to regenerate): $repo/$config_file"
			fi

			# Refresh each managed path from source
			local mp_path
			for mp_path in "${_MANAGED_MANIFEST_PATHS[@]}"; do
				# AGENTS.md is preserved on re-install without --force
				if [[ "$mp_path" == "AGENTS.md" && "$_saved_force" != "1" ]]; then
					_managed_track_file "$repo/AGENTS.md"
					log "kept existing AGENTS.md (use --force to refresh): $repo/AGENTS.md"
					continue
				fi
				sync_managed_path_from_manifest "$repo" "$mp_path" "$SOURCE_DIR"
			done

			# Discover new source files not in old manifest
			local entry fname rel_path subpath dst_parent

			# AGENTS.md template (only when --force or newly discovered)
			if ! [[ " ${_MANAGED_MANIFEST_PATHS[*]} " == *" AGENTS.md "* ]]; then
				log "new managed path discovered: AGENTS.md"
				sync_managed_file "$SOURCE_DIR/base/AGENTS.md" "$repo/AGENTS.md"
			fi

			# Agent files (recursive — includes reference subdirectories)
			while IFS= read -r -d '' entry; do
				subpath="${entry#"$SOURCE_DIR"/base/opencode/agents/}"
				rel_path=".opencode/agents/$subpath"
				if ! [[ " ${_MANAGED_MANIFEST_PATHS[*]} " == *" $rel_path "* ]]; then
					log "new managed path discovered: $rel_path"
					dst_parent="$(dirname "$repo/$rel_path")"
					ensure_dir "$dst_parent"
					sync_managed_file "$entry" "$repo/$rel_path"
				fi
			done < <(find "$SOURCE_DIR/base/opencode/agents" -type f -print0)

			# Command files
			for entry in "$SOURCE_DIR/base/opencode/commands"/*.md; do
				[[ -f "$entry" ]] || continue
				fname="$(basename "$entry")"
				rel_path=".opencode/commands/$fname"
				if ! [[ " ${_MANAGED_MANIFEST_PATHS[*]} " == *" $rel_path "* ]]; then
					log "new managed path discovered: $rel_path"
					sync_managed_file "$entry" "$repo/$rel_path"
				fi
			done

			# Skill files (recursive — includes scripts subdirectories)
			while IFS= read -r -d '' entry; do
				subpath="${entry#"$SOURCE_DIR"/base/opencode/skills/}"
				rel_path=".opencode/skills/$subpath"
				if ! [[ " ${_MANAGED_MANIFEST_PATHS[*]} " == *" $rel_path "* ]]; then
					log "new managed path discovered: $rel_path"
					dst_parent="$(dirname "$repo/$rel_path")"
					ensure_dir "$dst_parent"
					sync_managed_file "$entry" "$repo/$rel_path"
				fi
			done < <(find "$SOURCE_DIR/base/opencode/skills" -type f -print0)

			# Plugin files (recursive — includes scripts subdirectories)
			while IFS= read -r -d '' entry; do
				subpath="${entry#"$SOURCE_DIR"/base/opencode/plugins/}"
				rel_path=".opencode/plugins/$subpath"
				if ! [[ " ${_MANAGED_MANIFEST_PATHS[*]} " == *" $rel_path "* ]]; then
					log "new managed path discovered: $rel_path"
					dst_parent="$(dirname "$repo/$rel_path")"
					ensure_dir "$dst_parent"
					sync_managed_file "$entry" "$repo/$rel_path"
				fi
			done < <(find "$SOURCE_DIR/base/opencode/plugins" -type f -print0)

			# Rewrite base/opencode/ paths to .opencode/ in installed agent files
			[ -d "$repo/.opencode/agents" ] && find "$repo/.opencode/agents" -type f -name '*.md' -exec sed -i 's|base/opencode/|.opencode/|g' {} +

			finalize_managed_manifest "$repo"
			FORCE="$_saved_force"
			track_installed_project "$repo"
			log "repo bootstrap complete for: $repo"
			return
		else
			FORCE="$_saved_force"
			log "note: could not read existing manifest, falling back to full sync"
		fi
	fi
	# --- End manifest-aware refresh ---

	# Full install (fresh install or fallback)
	sync_generated_opencode_jsonc "$repo" "$RUNTIME"
	sync_managed_file "$SOURCE_DIR/base/AGENTS.md" "$repo/AGENTS.md"
	sync_managed_tree "$SOURCE_DIR/base/opencode/agents" "$repo/.opencode/agents" 1

	# Rewrite base/opencode/ paths to .opencode/ in installed agent files
	[ -d "$repo/.opencode/agents" ] && find "$repo/.opencode/agents" -type f -name '*.md' -exec sed -i 's|base/opencode/|.opencode/|g' {} +

	sync_managed_tree "$SOURCE_DIR/base/opencode/commands" "$repo/.opencode/commands" 1
	sync_managed_tree "$SOURCE_DIR/base/opencode/skills" "$repo/.opencode/skills" 1
	sync_managed_tree "$SOURCE_DIR/base/opencode/plugins" "$repo/.opencode/plugins" 1

	track_installed_project "$repo"

	finalize_managed_manifest "$repo"
	log "repo bootstrap complete for: $repo"
}

usage() {
	cat <<'EOF'
Usage:
  ./install/bootstrap.sh --repo <path> [--providers <list>] [--model <provider/model>] [--small-model <provider/model>] [--agent-preset <name>] [--dry-run] [--force]

Options:
  --repo <path>  Link OpenCode config into a target project.
  --providers    Provider set to enable: openai | github-copilot | laberit | opencode-go | free-tier | comma-separated combinations (default: free-tier for opencode)
  --model        Override default model (must belong to an enabled provider)
  --small-model  Override default small model (must belong to an enabled provider)
  --agent-preset Optional agent profile: balanced | fast | thorough (default: balanced behavior)
  --runtime      Runtime to configure: opencode (default) or kilocode.
  --ref <ref>    Fetch source from a specific Git ref (tag, branch, commit) on GitHub.
                 Without --ref, installs from the local ai-config source tree.
  --dry-run      Print planned operations without modifying files.
  --force        Refresh managed targets and generated runtime trees; preserve unmanaged local files.
  -h, --help     Show this help.
EOF
}

if [[ $# -eq 0 ]]; then
	usage
	exit 1
fi

while [[ $# -gt 0 ]]; do
	case "$1" in
	--repo)
		REPO_PATH="${2:-}"
		if [[ -z "$REPO_PATH" ]]; then
			log "error: --repo requires a path"
			exit 1
		fi
		shift 2
		;;
	--dry-run)
		DRY_RUN=1
		shift
		;;
	--providers)
		PROVIDERS_RAW="${2:-}"
		if [[ -z "$PROVIDERS_RAW" ]]; then
			log "error: --providers requires a value"
			exit 1
		fi
		shift 2
		;;
	--model)
		MODEL_OVERRIDE="${2:-}"
		if [[ -z "$MODEL_OVERRIDE" ]]; then
			log "error: --model requires a value"
			exit 1
		fi
		shift 2
		;;
	--small-model)
		SMALL_MODEL_OVERRIDE="${2:-}"
		if [[ -z "$SMALL_MODEL_OVERRIDE" ]]; then
			log "error: --small-model requires a value"
			exit 1
		fi
		shift 2
		;;
	--force)
		FORCE=1
		shift
		;;
	--agent-preset)
		AGENT_PRESET="${2:-}"
		if [[ -z "$AGENT_PRESET" ]]; then
			log "error: --agent-preset requires a value"
			exit 1
		fi
		shift 2
		;;
	--runtime)
		RUNTIME="${2:-}"
		if [[ -z "$RUNTIME" ]]; then
			log "error: --runtime requires a value"
			exit 1
		fi
		if [[ "$RUNTIME" != "opencode" && "$RUNTIME" != "kilocode" ]]; then
			log "error: invalid --runtime '$RUNTIME'. Allowed values: opencode, kilocode"
			exit 1
		fi
		shift 2
		;;
	--ref)
		INSTALL_REF="${2:-}"
		if [[ -z "$INSTALL_REF" ]]; then
			log "error: --ref requires a value"
			exit 1
		fi
		shift 2
		;;
	-h | --help)
		usage
		exit 0
		;;
	*)
		log "error: unknown option: $1"
		usage
		exit 1
		;;
	esac
done

if [[ -z "$REPO_PATH" ]]; then
	log "error: --repo <path> is required"
	exit 1
fi

# If --ref is provided, fetch the specified release source from GitHub
if [[ -n "$INSTALL_REF" ]]; then
	# Determine the source repo URL
	REPO_URL=""
	if command -v git &>/dev/null; then
		if REPO_URL="$(cd "$ROOT_DIR" && git remote get-url origin 2>/dev/null)"; then
			:
		else
			REPO_URL=""
		fi
	fi
	if [[ -z "$REPO_URL" ]]; then
		REPO_URL="https://github.com/Macacoders/ai-config.git"
	fi

	TEMP_DIR="$(mktemp -d 2>/dev/null || mktemp -d -t ai-config.XXXXXX)"
	if [[ -z "$TEMP_DIR" || ! -d "$TEMP_DIR" ]]; then
		log "error: could not create temp directory for --ref clone"
		exit 1
	fi

	log "fetching ref '${INSTALL_REF}' from ${REPO_URL} ..."
	if ! GIT_TERMINAL_PROMPT=0 GIT_ASKPASS=echo git clone --branch "$INSTALL_REF" --depth 1 "$REPO_URL" "$TEMP_DIR" 2>&1 | sed 's/^/[ai-config] /'; then
		log "error: failed to clone ref '${INSTALL_REF}' from ${REPO_URL}"
		log "       verify the ref exists and is reachable"
		rm -rf "$TEMP_DIR"
		exit 1
	fi

	SOURCE_DIR="$TEMP_DIR"
	# Re-read VERSION from the fetched release source
	AI_CONFIG_VERSION="$(cat "$SOURCE_DIR/VERSION" 2>/dev/null || echo "0.0.0")"

	# Clean up temp dir on exit
	trap 'rm -rf "$TEMP_DIR"' EXIT
	log "using release source from ref '${INSTALL_REF}' (version ${AI_CONFIG_VERSION})"
fi

install_repo "$REPO_PATH"
log "done"
