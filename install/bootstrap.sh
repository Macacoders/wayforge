#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
source "$SCRIPT_DIR/lib/managed_sync.sh"

DRY_RUN=0
FORCE=0
REPO_PATH=""
PROVIDERS_RAW="openai"
MODEL_OVERRIDE=""
SMALL_MODEL_OVERRIDE=""
RUNTIME="opencode"
AGENT_PRESET=""

MANAGED_OPENCODE_HEADER='// Generated by ai-config bootstrap.sh'
MANAGED_DIR_MARKER='.ai-config-managed'

log() {
  printf '[ai-config] %s\n' "$*"
}

safe_link() {
  local src="$1"
  local dst="$2"

  if [[ ! -e "$src" ]]; then
    log "error: source does not exist: $src"
    exit 1
  fi

  if [[ -L "$dst" ]]; then
    local current
    current="$(readlink "$dst")"
    if [[ "$current" == "$src" && "$FORCE" -eq 0 ]]; then
      log "kept existing symlink: $dst -> $src"
      return
    fi

    if [[ "$FORCE" -eq 1 ]]; then
      run_rm "$dst"
      run_ln "$src" "$dst"
      if [[ "$DRY_RUN" -eq 1 ]]; then
        log "DRY-RUN: would replace symlink: $dst -> $src"
      else
        log "linked (replaced symlink): $dst -> $src"
      fi
      return
    fi

    log "skip existing symlink (use --force to replace): $dst -> $current"
    return
  fi

  if [[ -e "$dst" ]]; then
    log "skip existing non-symlink: $dst"
    return
  fi

  local parent
  parent="$(dirname "$dst")"
  ensure_dir "$parent"
  run_ln "$src" "$dst"
  if [[ "$DRY_RUN" -eq 1 ]]; then
    log "DRY-RUN: would link: $dst -> $src"
  else
    log "linked: $dst -> $src"
  fi
}

contains_provider() {
  local needle="$1"
  local item
  for item in "${SELECTED_PROVIDERS[@]}"; do
    if [[ "$item" == "$needle" ]]; then
      return 0
    fi
  done
  return 1
}

parse_providers() {
  local raw="$1"
  local token
  local seen_openai=0
    local seen_github_copilot=0
  local seen_laberit=0

  IFS=',' read -r -a _providers_in <<<"$raw"
  SELECTED_PROVIDERS=()

  for token in "${_providers_in[@]}"; do
    case "$token" in
      openai)
        if [[ "$seen_openai" -eq 0 ]]; then
          SELECTED_PROVIDERS+=("openai")
          seen_openai=1
        fi
        ;;
      github-copilot)
        if [[ "$seen_github_copilot" -eq 0 ]]; then
          SELECTED_PROVIDERS+=("github-copilot")
          seen_github_copilot=1
        fi
        ;;
      laberit)
        if [[ "$seen_laberit" -eq 0 ]]; then
          SELECTED_PROVIDERS+=("laberit")
          seen_laberit=1
        fi
        ;;
      *)
        log "error: invalid provider '$token' in --providers"
        log "       allowed values: openai, github-copilot, laberit, or comma-separated combinations"
        exit 1
        ;;
    esac
  done

  if [[ "${#SELECTED_PROVIDERS[@]}" -eq 0 ]]; then
    log "error: --providers must include at least one provider"
    exit 1
  fi
}

validate_model_override() {
  local value="$1"
  local flag_name="$2"
  if [[ -z "$value" ]]; then
    return
  fi

  local provider="${value%%/*}"
  if [[ "$provider" == "$value" ]]; then
    log "error: $flag_name must be in '<provider>/<model>' format"
    exit 1
  fi

  if ! contains_provider "$provider"; then
    log "error: $flag_name provider '$provider' is not enabled by --providers"
    exit 1
  fi
}

validate_agent_preset() {
  local value="$1"
  if [[ -z "$value" ]]; then
    return
  fi

  case "$value" in
    balanced|fast|thorough)
      ;;
    *)
      log "error: invalid --agent-preset '$value'. Allowed values: balanced, fast, thorough"
      exit 1
      ;;
  esac
}

pick_planner_model() {
  if contains_provider "openai"; then
    printf 'openai/gpt-5.5'
    return
  fi
  if contains_provider "github-copilot"; then
    printf 'github-copilot/gpt-5.4'
    return
  fi
  printf 'laberit/laberit-ai-preview'
}

