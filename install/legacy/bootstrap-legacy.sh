#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
SOURCE_DIR="$ROOT_DIR"
AI_CONFIG_VERSION="$(cat "$SOURCE_DIR/VERSION" 2>/dev/null || echo "0.0.0")"
# shellcheck source=install/lib/managed_sync.sh
source "$SCRIPT_DIR/lib/managed_sync.sh"

DRY_RUN=0
FORCE=0
NO_TRACK=0
REPO_PATH=""
PROVIDERS_RAW="free-tier"
MODEL_OVERRIDE=""
SMALL_MODEL_OVERRIDE=""
RUNTIME="opencode"
INSTALL_REF=""
GH_APP_CLIENT_ID=""

MANAGED_OPENCODE_HEADER='// Generated by ai-config bootstrap'
MANAGED_DIR_MARKER='.ai-config-managed'

log() {
	printf '[ai-config] %s\n' "$*"
}

contains_provider() {
	local needle="$1"
	local item
	for item in "${SELECTED_PROVIDERS[@]}"; do
		if [[ "$item" == "$needle" ]]; then
			return 0
		fi
	done
	return 1
}

has_real_provider() {
	local p
	for p in "${SELECTED_PROVIDERS[@]}"; do
		if [[ "$p" != "free-tier" ]]; then
			return 0
		fi
	done
	return 1
}

validate_free_tier_runtime() {
	if contains_provider "free-tier" && [[ "$RUNTIME" != "opencode" ]]; then
		log "error: free-tier provider is only available for opencode runtime"
		exit 1
	fi
}

parse_providers() {
	local raw="$1"
	local token
	local seen_openai=0
	local seen_github_copilot=0
	local seen_laberit=0
	local seen_opencode_go=0
	local seen_free_tier=0

	IFS=',' read -r -a _providers_in <<<"$raw"
	SELECTED_PROVIDERS=()

	for token in "${_providers_in[@]}"; do
		case "$token" in
		openai)
			if [[ "$seen_openai" -eq 0 ]]; then
				SELECTED_PROVIDERS+=("openai")
				seen_openai=1
			fi
			;;
		github-copilot)
			if [[ "$seen_github_copilot" -eq 0 ]]; then
				SELECTED_PROVIDERS+=("github-copilot")
				seen_github_copilot=1
			fi
			;;
		laberit)
			if [[ "$seen_laberit" -eq 0 ]]; then
				SELECTED_PROVIDERS+=("laberit")
				seen_laberit=1
			fi
			;;
		opencode-go)
			if [[ "$seen_opencode_go" -eq 0 ]]; then
				SELECTED_PROVIDERS+=("opencode-go")
				seen_opencode_go=1
			fi
			;;
		free-tier)
			if [[ "$seen_free_tier" -eq 0 ]]; then
				SELECTED_PROVIDERS+=("free-tier")
				seen_free_tier=1
			fi
			;;
		*)
			log "error: invalid provider '$token' in --providers"
			log "       allowed values: openai, github-copilot, laberit, opencode-go, free-tier, or comma-separated combinations"
			exit 1
			;;
		esac
	done

	if [[ "${#SELECTED_PROVIDERS[@]}" -eq 0 ]]; then
		log "error: --providers must include at least one provider"
		exit 1
	fi
}

validate_model_override() {
	local value="$1"
	local flag_name="$2"
	if [[ -z "$value" ]]; then
		return
	fi

	local provider="${value%%/*}"
	if [[ "$provider" == "$value" ]]; then
		log "error: $flag_name must be in '<provider>/<model>' format"
		exit 1
	fi

	if ! contains_provider "$provider"; then
		log "error: $flag_name provider '$provider' is not enabled by --providers"
		exit 1
	fi
}

is_temp_path() {
	local path="$1"

	# Check well-known Unix temp directories
	case "$path" in
	/tmp/* | /tmp) return 0 ;;
	/var/tmp/* | /var/tmp) return 0 ;;
	esac

	# Check TMPDIR environment variable
	if [[ -n "${TMPDIR:-}" ]]; then
		case "$path" in
		"${TMPDIR}"/* | "${TMPDIR}") return 0 ;;
		esac
	fi

	# On Windows (Git Bash/MSYS2), check %TEMP%
	local win_temp
	if command -v cmd &>/dev/null; then
		win_temp="$(cmd //c "echo %TEMP%" 2>/dev/null | tr -d '\r\n')"
		if [[ -n "$win_temp" && -d "$win_temp" ]]; then
			local win_temp_canonical
			win_temp_canonical="$(cd "$win_temp" 2>/dev/null && pwd -P || echo "$win_temp")"
			case "$path" in
			"${win_temp_canonical}"/* | "${win_temp_canonical}") return 0 ;;
			esac
		fi
	fi

	return 1
}

track_installed_project() {
	local path="$1"
	[[ "$DRY_RUN" -eq 1 ]] && return
	[[ "$FORCE" -eq 1 ]] && return
	[[ "$NO_TRACK" -eq 1 ]] && return

	local tracking_file="$ROOT_DIR/installed-projects.json"
	local canonical name timestamp escaped_path

	canonical=$(realpath "$path" 2>/dev/null || (cd "$path" && pwd -P))

	# Convert to Windows-native format for cross-platform compatibility
	if command -v wslpath &>/dev/null; then
		canonical=$(wslpath -w "$canonical" 2>/dev/null || printf '%s' "$canonical")
	fi

	# Skip tracking for temporary/debug paths
	if is_temp_path "$canonical"; then
		log "skip tracking temporary/debug path: $canonical"
		return
	fi

	name=$(basename "$canonical")
	timestamp=$(TZ='Europe/Berlin' date +'%Y-%m-%dT%H:%M:%S%z' | sed 's/\(..\)$/:\1/')
	local install_ref="${INSTALL_REF:-develop}"

	# Escape backslashes for JSON string values (e.g. C:\path → C:\\path)
	escaped_path=$(printf '%s' "$canonical" | sed 's/\\/\\\\/g')

	if [[ ! -f "$tracking_file" ]]; then
		# Create tracking file with envelope and initial project entry
		{
			printf '{\n'
			printf '  "schemaVersion": "1.0.0",\n'
			printf '  "projects": [\n'
			printf '    {\n'
			printf '      "name": "%s",\n' "$name"
			printf '      "path": "%s",\n' "$escaped_path"
			printf '      "lastUpdated": "%s",\n' "$timestamp"
			printf '      "aiConfigVersion": "%s",\n' "$AI_CONFIG_VERSION"
			printf '      "installRef": "%s"\n' "$install_ref"
			printf '    }\n'
			printf '  ]\n'
			printf '}\n'
		} >"$tracking_file"
		log "tracked installed project: $canonical"
		return 0
	fi

	# Duplicate check: exact path match in existing entries
	if grep -Fq '"path": "'"$escaped_path"'"' "$tracking_file" 2>/dev/null; then
		return 0
	fi

	# Append new entry — read file, drop closing "  ]" and "}", insert new entry
	local tmpfile="${tracking_file}.tmp"
	local lines=()

	while IFS= read -r line; do
		lines+=("$line")
	done <"$tracking_file"

	local total=${#lines[@]}

	# Write all lines except the last three (last entry's "}", "  ]", "}")
	for ((i = 0; i < total - 3; i++)); do
		printf '%s\n' "${lines[$i]}" >>"$tmpfile"
	done

	if ((total > 5)); then
		# Existing entries present: turn the previous "    }" into "    },"
		printf '    },\n' >>"$tmpfile"
	else
		# No entries yet: write the "  "projects": [" header line
		printf '%s\n' "${lines[$total - 3]}" >>"$tmpfile"
	fi

	# Write the new project entry
	{
		printf '    {\n'
		printf '      "name": "%s",\n' "$name"
		printf '      "path": "%s",\n' "$escaped_path"
		printf '      "lastUpdated": "%s",\n' "$timestamp"
		printf '      "aiConfigVersion": "%s",\n' "$AI_CONFIG_VERSION"
		printf '      "installRef": "%s"\n' "$install_ref"
		printf '    }\n'
	} >>"$tmpfile"

	# Close the JSON structure
	{
		printf '  ]\n'
		printf '}\n'
	} >>"$tmpfile"

	mv "$tmpfile" "$tracking_file"
	log "tracked installed project: $canonical"
}

build_enabled_providers_json() {
	local out=""
	local first=1

	if [[ "$RUNTIME" == "opencode" ]]; then
		out="\"opencode\""
		first=0
	fi

	local provider
	for provider in "${SELECTED_PROVIDERS[@]}"; do
		# free-tier is an installer-only concept, not a real OpenCode provider
		[[ "$provider" == "free-tier" ]] && continue
		if [[ "$first" -eq 1 ]]; then
			out="\"$provider\""
			first=0
		else
			out="$out, \"$provider\""
		fi
	done
	printf '%s' "$out"
}

build_provider_block_json() {
	local provider_fragment_dir="$SOURCE_DIR/base/opencode/config/providers"
	read_fragment() {
		local name="$1"
		local file="$provider_fragment_dir/$name"
		if [[ ! -f "$file" ]]; then
			log "error: missing provider config fragment: $file"
			exit 1
		fi
		printf '%s' "$(<"$file")"
	}

	local out=""

	if [[ "$RUNTIME" == "opencode" ]]; then
		out="$(read_fragment 'opencode-provider-block.jsonc')"
	fi

	if contains_provider "openai"; then
		local openai_block
		openai_block="$(read_fragment 'openai-provider-block.jsonc')"

		if [[ -n "$out" ]]; then
			out="$out,
$openai_block"
		else
			out="$openai_block"
		fi
	fi

	if contains_provider "github-copilot"; then
		local copilot_block
		copilot_block="$(read_fragment 'github-copilot-provider-block.jsonc')"

		if [[ -n "$out" ]]; then
			out="$out,
$copilot_block"
		else
			out="$copilot_block"
		fi
	fi

	if contains_provider "laberit"; then
		local laberit_block
		laberit_block="$(read_fragment 'laberit-provider-block.jsonc')"

		if [[ -n "$out" ]]; then
			out="$out,
$laberit_block"
		else
			out="$laberit_block"
		fi
	fi

	if contains_provider "opencode-go"; then
		local opencode_go_block
		opencode_go_block="$(read_fragment 'opencode-go-provider-block.jsonc')"

		if [[ -n "$out" ]]; then
			out="$out,
$opencode_go_block"
		else
			out="$opencode_go_block"
		fi
	fi

	printf '%s' "$out"
}

read_agent_fragment() {
	local file="$SOURCE_DIR/base/opencode/config/agents/$1"
	if [[ ! -f "$file" ]]; then
		log "error: missing agent config fragment: $file"
		exit 1
	fi
	printf '%s' "$(<"$file")"
}

build_agent_block_json() {
	if contains_provider "openai" && contains_provider "github-copilot"; then
		read_agent_fragment 'balanced-openai-github-copilot-agent-block.jsonc'
		return
	fi

	if [[ "${#SELECTED_PROVIDERS[@]}" -eq 1 && "${SELECTED_PROVIDERS[0]}" == "github-copilot" ]]; then
		read_agent_fragment 'balanced-github-copilot-only-agent-block.jsonc'
		return
	fi

	if [[ "${#SELECTED_PROVIDERS[@]}" -eq 1 && "${SELECTED_PROVIDERS[0]}" == "laberit" ]]; then
		read_agent_fragment 'balanced-laberit-only-agent-block.jsonc'
		return
	fi

	if [[ "${#SELECTED_PROVIDERS[@]}" -eq 1 && "${SELECTED_PROVIDERS[0]}" == "opencode-go" ]]; then
		read_agent_fragment 'balanced-opencode-go-only-agent-block.jsonc'
		return
	fi

	if ! has_real_provider; then
		return
	fi

	read_agent_fragment 'balanced-openai-only-agent-block.jsonc'
}

generate_opencode_jsonc_content() {
	local runtime="${1:-opencode}"
	local default_model="openai/gpt-5.5"
	local default_small_model="openai/gpt-5.4-mini"

	if [[ "${#SELECTED_PROVIDERS[@]}" -eq 1 && "${SELECTED_PROVIDERS[0]}" == "github-copilot" ]]; then
		default_model="github-copilot/gpt-5.4"
		default_small_model="github-copilot/gpt-5.3-codex"
	fi

	if contains_provider "openai" && contains_provider "github-copilot"; then
		default_model="openai/gpt-5.5"
		default_small_model="github-copilot/gemini-3.5-flash"
	fi

	if [[ "${#SELECTED_PROVIDERS[@]}" -eq 1 && "${SELECTED_PROVIDERS[0]}" == "laberit" ]]; then
		default_model="laberit/laberit-ai-preview"
		default_small_model="laberit/laberit-ai"
	fi

	if [[ "${#SELECTED_PROVIDERS[@]}" -eq 1 && "${SELECTED_PROVIDERS[0]}" == "opencode-go" ]]; then
		default_model="opencode-go/deepseek-v4-pro"
		default_small_model="opencode-go/deepseek-v4-flash"
	fi

	if ! has_real_provider; then
		default_model=""
		default_small_model=""
	fi

	local final_model="$default_model"
	local final_small_model="$default_small_model"
	if [[ -n "$MODEL_OVERRIDE" ]]; then
		final_model="$MODEL_OVERRIDE"
	fi
	if [[ -n "$SMALL_MODEL_OVERRIDE" ]]; then
		final_small_model="$SMALL_MODEL_OVERRIDE"
	fi

	local schema_url="https://opencode.ai/config.json"
	if [[ "$runtime" == "kilocode" ]]; then
		schema_url="https://app.kilo.ai/config.json"
	fi

	local enabled_json
	enabled_json="$(build_enabled_providers_json)"
	local provider_block
	provider_block="$(build_provider_block_json)"
	local agent_block
	agent_block="$(build_agent_block_json)"
	local agent_section=""
	if [[ -n "$agent_block" ]]; then
		agent_section="${agent_block},
  "
	fi

	cat <<EOF
$MANAGED_OPENCODE_HEADER
{
  "\$schema": "$schema_url",
  "enabled_providers": [$enabled_json],
  "model": "$final_model",
  "small_model": "$final_small_model",
  "default_agent": "planner",
  "share": "disabled",
  $agent_section"provider": {
$provider_block
  },
  "plugin": ["./.opencode/plugins/ponytail/ponytail.mjs"],
  "permission": {
    "skill": {
      "*": "allow"
    }
  }
}
EOF
}

sync_generated_opencode_jsonc() {
	local repo="$1"
	local runtime="$2"
	local config_file="opencode.jsonc"
	if [[ "$runtime" == "kilocode" ]]; then
		config_file="kilo.jsonc"
	fi
	local dst="$repo/$config_file"
	local parent
	parent="$(dirname "$dst")"
	ensure_dir "$parent"

	if [[ -L "$dst" ]]; then
		if [[ "$FORCE" -ne 1 ]]; then
			log "skip existing symlink (use --force to replace): $dst -> $(readlink "$dst")"
			return
		fi
		run_rm "$dst"
	elif [[ -e "$dst" ]]; then
		if [[ "$FORCE" -ne 1 ]]; then
			log "skip existing non-symlink (use --force to regenerate): $dst"
			return
		fi
		# FORCE=1: regenerate regardless of managed status (fresh-install behavior)
	fi

	local content
	content="$(generate_opencode_jsonc_content "$runtime")"
	run_write_file "$dst" "$content"
	if [[ "$DRY_RUN" -eq 1 ]]; then
		log "DRY-RUN: would generate local config: $dst"
	else
		log "generated local config: $dst"
	fi
}

install_repo() {
	local repo="$1"

	if [[ ! -d "$repo" ]]; then
		log "error: repo path does not exist: $repo"
		exit 1
	fi

	ensure_dir "$repo/.opencode"

	parse_providers "$PROVIDERS_RAW"
	validate_free_tier_runtime
	validate_model_override "$MODEL_OVERRIDE" "--model"
	validate_model_override "$SMALL_MODEL_OVERRIDE" "--small-model"

	init_managed_manifest "$repo" "$AI_CONFIG_VERSION" "$INSTALL_REF"

	# --- Manifest-aware selective refresh ---
	if [[ -f "$repo/.ai-config-managed" ]]; then
		log "existing install detected, refreshing managed paths from manifest"

		# Allow refresh even without --force (files are known managed)
		local _saved_force="$FORCE"
		FORCE=1

		if read_managed_manifest "$repo"; then
			# Regenerate runtime config only with --force (fresh-install behavior)
			local config_file="opencode.jsonc"
			[[ "$RUNTIME" == "kilocode" ]] && config_file="kilo.jsonc"
			if [[ "$_saved_force" = "1" ]]; then
				sync_generated_opencode_jsonc "$repo" "$RUNTIME"
			else
				log "kept existing $config_file (use --force to regenerate): $repo/$config_file"
			fi

			# Refresh each managed path from source
			local mp_path
			for mp_path in "${_MANAGED_MANIFEST_PATHS[@]}"; do
				# AGENTS.md is preserved on re-install without --force
				if [[ "$mp_path" == "AGENTS.md" && "$_saved_force" != "1" ]]; then
					_managed_track_file "$repo/AGENTS.md"
					log "kept existing AGENTS.md (use --force to refresh): $repo/AGENTS.md"
					continue
				fi
				sync_managed_path_from_manifest "$repo" "$mp_path" "$SOURCE_DIR"
			done

			# Discover new source files not in old manifest
			local entry fname rel_path subpath dst_parent

			# AGENTS.md template (only when --force or newly discovered)
			if ! [[ " ${_MANAGED_MANIFEST_PATHS[*]} " == *" AGENTS.md "* ]]; then
				log "new managed path discovered: AGENTS.md"
				sync_managed_file "$SOURCE_DIR/base/AGENTS.md" "$repo/AGENTS.md"
			fi

			# Agent files (recursive — includes reference subdirectories)
			while IFS= read -r -d '' entry; do
				subpath="${entry#"$SOURCE_DIR"/base/opencode/agents/}"
				rel_path=".opencode/agents/$subpath"
				if ! [[ " ${_MANAGED_MANIFEST_PATHS[*]} " == *" $rel_path "* ]]; then
					log "new managed path discovered: $rel_path"
					dst_parent="$(dirname "$repo/$rel_path")"
					ensure_dir "$dst_parent"
					sync_managed_file "$entry" "$repo/$rel_path"
				fi
			done < <(find "$SOURCE_DIR/base/opencode/agents" -type f -print0)

			# Command files
			for entry in "$SOURCE_DIR/base/opencode/commands"/*.md; do
				[[ -f "$entry" ]] || continue
				fname="$(basename "$entry")"
				rel_path=".opencode/commands/$fname"
				if ! [[ " ${_MANAGED_MANIFEST_PATHS[*]} " == *" $rel_path "* ]]; then
					log "new managed path discovered: $rel_path"
					sync_managed_file "$entry" "$repo/$rel_path"
				fi
			done

			# Skill files (recursive — includes scripts subdirectories)
			while IFS= read -r -d '' entry; do
				subpath="${entry#"$SOURCE_DIR"/base/opencode/skills/}"
				rel_path=".opencode/skills/$subpath"
				if ! [[ " ${_MANAGED_MANIFEST_PATHS[*]} " == *" $rel_path "* ]]; then
					log "new managed path discovered: $rel_path"
					dst_parent="$(dirname "$repo/$rel_path")"
					ensure_dir "$dst_parent"
					sync_managed_file "$entry" "$repo/$rel_path"
				fi
			done < <(find "$SOURCE_DIR/base/opencode/skills" -type f -print0)

			# Plugin files (recursive — includes scripts subdirectories)
			while IFS= read -r -d '' entry; do
				subpath="${entry#"$SOURCE_DIR"/base/opencode/plugins/}"
				rel_path=".opencode/plugins/$subpath"
				if ! [[ " ${_MANAGED_MANIFEST_PATHS[*]} " == *" $rel_path "* ]]; then
					log "new managed path discovered: $rel_path"
					dst_parent="$(dirname "$repo/$rel_path")"
					ensure_dir "$dst_parent"
					sync_managed_file "$entry" "$repo/$rel_path"
				fi
			done < <(find "$SOURCE_DIR/base/opencode/plugins" -type f -print0)

			# Rewrite base/opencode/ paths to .opencode/ in installed agent files
			[ -d "$repo/.opencode/agents" ] && find "$repo/.opencode/agents" -type f -name '*.md' -exec sed -i 's|base/opencode/|.opencode/|g' {} +

			# Inject/refresh centralized permissions into managed agent markdown frontmatter
			local agent_md agent_name
			for agent_md in "$repo/.opencode/agents"/*.md; do
				[[ -f "$agent_md" ]] || continue
				if ! is_managed_file "$agent_md"; then continue; fi
				agent_name="${agent_md##*/}"
				agent_name="${agent_name%.md}"
				local tmp_perm="${agent_md}.perm-tmp"
				render_agent_with_central_permissions "$agent_md" "$tmp_perm" "$agent_name" "$SOURCE_DIR/base/opencode/permissions/agents.yml"
				mv "$tmp_perm" "$agent_md"
			done

			finalize_managed_manifest "$repo"
			FORCE="$_saved_force"
			track_installed_project "$repo"
			log "repo bootstrap complete for: $repo"
			return
		else
			FORCE="$_saved_force"
			log "note: could not read existing manifest, falling back to full sync"
		fi
	fi
	# --- End manifest-aware refresh ---

	# Full install (fresh install or fallback)
	sync_generated_opencode_jsonc "$repo" "$RUNTIME"
	sync_managed_file "$SOURCE_DIR/base/AGENTS.md" "$repo/AGENTS.md"
	sync_agents_tree_with_permissions "$SOURCE_DIR/base/opencode/agents" "$repo/.opencode/agents" "$SOURCE_DIR/base/opencode/permissions/agents.yml"

	# Rewrite base/opencode/ paths to .opencode/ in installed agent files
	[ -d "$repo/.opencode/agents" ] && find "$repo/.opencode/agents" -type f -name '*.md' -exec sed -i 's|base/opencode/|.opencode/|g' {} +

	sync_managed_tree "$SOURCE_DIR/base/opencode/commands" "$repo/.opencode/commands" 1
	sync_managed_tree "$SOURCE_DIR/base/opencode/skills" "$repo/.opencode/skills" 1
	sync_managed_tree "$SOURCE_DIR/base/opencode/plugins" "$repo/.opencode/plugins" 1

	# --- GitHub App Client ID ---
	local app_yml="$repo/.gh-config/app.yml"
	ensure_dir "$(dirname "$app_yml")"
	if [[ -n "$GH_APP_CLIENT_ID" ]]; then
		if [[ "$DRY_RUN" -eq 1 ]]; then
			log "DRY-RUN: would write GitHub App Client ID to $app_yml"
		else
			cat >"$app_yml" <<APPCFG
# GitHub App Client ID for OAuth Device Flow.
# Generated by ai-config installer.
client_id: $GH_APP_CLIENT_ID
APPCFG
			log "wrote GitHub App Client ID to $app_yml"
		fi
	else
		if [[ ! -f "$app_yml" ]]; then
			if [[ "$DRY_RUN" -eq 1 ]]; then
				log "DRY-RUN: would write GitHub App Client ID template to $app_yml"
			else
				cat >"$app_yml" <<'APPCFG'
# GitHub App Client ID for OAuth Device Flow.
# 
# To enable issue management with /issue:
#   1. Go to https://github.com/settings/apps -> New GitHub App
#   2. Set permissions: Issues (Read & Write), Pull Requests (Read & Write)
#   3. Under "Identifying and authorizing users", enable Device Flow
#   4. Save, copy the Client ID (starts with "Iv1")
#   5. Install the app on this repository/organization
#   6. Uncomment and fill in below:
# client_id: 
APPCFG
				log "created GitHub App Client ID template at $app_yml (fill in your Client ID)"
			fi
		fi
	fi

	track_installed_project "$repo"

	finalize_managed_manifest "$repo"
	log "repo bootstrap complete for: $repo"
}

usage() {
	cat <<'EOF'
Usage:
  ./install/bootstrap.sh --repo <path> [--providers <list>] [--model <provider/model>] [--small-model <provider/model>] [--dry-run] [--force]

Options:
  --repo <path>  Link OpenCode config into a target project.
  --providers    Provider set to enable: openai | github-copilot | laberit | opencode-go | free-tier | comma-separated combinations (default: free-tier for opencode)
  --model        Override default model (must belong to an enabled provider)
  --small-model  Override default small model (must belong to an enabled provider)
  --runtime      Runtime to configure: opencode (default) or kilocode.
  --ref <ref>    Fetch source from a specific Git ref (tag, branch, commit) on GitHub.
                 Without --ref, installs from the local ai-config source tree.
  --gh-app-client-id <id>   GitHub App Client ID for issue management (Iv1...). Creates .gh-config/app.yml.
  --dry-run      Print planned operations without modifying files.
  --force        Refresh managed targets and generated runtime trees; preserve unmanaged local files.
  --no-track     Skip recording this project in installed-projects.json.
  -h, --help     Show this help.
EOF
}

if [[ $# -eq 0 ]]; then
	usage
	exit 1
fi

while [[ $# -gt 0 ]]; do
	case "$1" in
	--repo)
		REPO_PATH="${2:-}"
		if [[ -z "$REPO_PATH" ]]; then
			log "error: --repo requires a path"
			exit 1
		fi
		shift 2
		;;
	--dry-run)
		DRY_RUN=1
		shift
		;;
	--providers)
		PROVIDERS_RAW="${2:-}"
		if [[ -z "$PROVIDERS_RAW" ]]; then
			log "error: --providers requires a value"
			exit 1
		fi
		shift 2
		;;
	--model)
		MODEL_OVERRIDE="${2:-}"
		if [[ -z "$MODEL_OVERRIDE" ]]; then
			log "error: --model requires a value"
			exit 1
		fi
		shift 2
		;;
	--small-model)
		SMALL_MODEL_OVERRIDE="${2:-}"
		if [[ -z "$SMALL_MODEL_OVERRIDE" ]]; then
			log "error: --small-model requires a value"
			exit 1
		fi
		shift 2
		;;
	--force)
		FORCE=1
		shift
		;;
	--no-track)
		NO_TRACK=1
		shift
		;;
	--runtime)
		RUNTIME="${2:-}"
		if [[ -z "$RUNTIME" ]]; then
			log "error: --runtime requires a value"
			exit 1
		fi
		if [[ "$RUNTIME" != "opencode" && "$RUNTIME" != "kilocode" ]]; then
			log "error: invalid --runtime '$RUNTIME'. Allowed values: opencode, kilocode"
			exit 1
		fi
		shift 2
		;;
	--ref)
		INSTALL_REF="${2:-}"
		if [[ -z "$INSTALL_REF" ]]; then
			log "error: --ref requires a value"
			exit 1
		fi
		shift 2
		;;
	--gh-app-client-id)
		GH_APP_CLIENT_ID="${2:-}"
		if [[ -z "$GH_APP_CLIENT_ID" ]]; then
			log "error: --gh-app-client-id requires a value"
			exit 1
		fi
		shift 2
		;;
	-h | --help)
		usage
		exit 0
		;;
	*)
		log "error: unknown option: $1"
		usage
		exit 1
		;;
	esac
done

if [[ -z "$REPO_PATH" ]]; then
	log "error: --repo <path> is required"
	exit 1
fi

# If --ref is provided, fetch the specified release source from GitHub
if [[ -n "$INSTALL_REF" ]]; then
	# Determine the source repo URL
	REPO_URL=""
	if command -v git &>/dev/null; then
		if REPO_URL="$(cd "$ROOT_DIR" && git remote get-url origin 2>/dev/null)"; then
			:
		else
			REPO_URL=""
		fi
	fi
	if [[ -z "$REPO_URL" ]]; then
		REPO_URL="https://github.com/Macacoders/ai-config.git"
	fi

	TEMP_DIR="$(mktemp -d 2>/dev/null || mktemp -d -t ai-config.XXXXXX)"
	if [[ -z "$TEMP_DIR" || ! -d "$TEMP_DIR" ]]; then
		log "error: could not create temp directory for --ref clone"
		exit 1
	fi

	log "fetching ref '${INSTALL_REF}' from ${REPO_URL} ..."
	if ! GIT_TERMINAL_PROMPT=0 GIT_ASKPASS=echo git clone --branch "$INSTALL_REF" --depth 1 "$REPO_URL" "$TEMP_DIR" 2>&1 | sed 's/^[ai-config] /'; then
		log "error: failed to clone ref '${INSTALL_REF}' from ${REPO_URL}"
		log "       verify the ref exists and is reachable"
		rm -rf "$TEMP_DIR"
		exit 1
	fi

	SOURCE_DIR="$TEMP_DIR"
	# Re-read VERSION from the fetched release source
	AI_CONFIG_VERSION="$(cat "$SOURCE_DIR/VERSION" 2>/dev/null || echo "0.0.0")"

	# Clean up temp dir on exit
	trap 'rm -rf "$TEMP_DIR"' EXIT
	log "using release source from ref '${INSTALL_REF}' (version ${AI_CONFIG_VERSION})"
fi

install_repo "$REPO_PATH"
log "done"
