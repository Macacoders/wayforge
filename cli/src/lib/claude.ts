import fs from 'fs-extra'
import path from 'path'
import type { ManifestContext } from './context.js'
import { CLAUDE_MEMORY_FILE } from './layout.js'
import { syncManagedContent } from './manifest.js'

/**
 * Write the Claude Code memory entrypoint (`CLAUDE.md`).
 *
 * Claude Code reads `AGENTS.md` directly on newer versions, but importing
 * `@AGENTS.md` from `CLAUDE.md` also covers older versions and sessions where
 * AGENTS.md support is unavailable. No workflow rules are duplicated here:
 * `AGENTS.md` stays the single source of truth.
 */
export function syncClaudeMemory(
	repo: string,
	sourceDir: string,
	ctx: ManifestContext,
): void {
	const agentsMd = path.join(sourceDir, 'base', 'AGENTS.md')
	if (!fs.pathExistsSync(agentsMd)) {
		ctx.log(`error: source file does not exist: ${agentsMd}`)
		process.exit(1)
	}

	const content = [
		'# CLAUDE.md',
		'',
		'@AGENTS.md',
		'',
		'<!-- Generated by wayforge. Do not edit; rerun `wfg install --runtime claude --force` to refresh. -->',
	]
	syncManagedContent(
		path.join(repo, CLAUDE_MEMORY_FILE),
		content.join('\n'),
		ctx,
	)
}
