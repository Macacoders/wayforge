export class ManifestContext {
  dryRun: boolean;
  force: boolean;
  repoRoot: string;
  noTrack: boolean;

  constructor(dryRun: boolean, force: boolean, noTrack: boolean) {
    this.dryRun = dryRun;
    this.force = force;
    this.repoRoot = "";
    this.noTrack = noTrack;
  }

  log(message: string): void {
    console.log(`[ai-config] ${message}`);
  }
}

