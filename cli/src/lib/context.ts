export class ManifestContext {
	dryRun: boolean
	force: boolean
	repoRoot: string
	noTrack: boolean
	projectId: string
	overrideUnmanaged: Set<string>

	constructor(dryRun: boolean, force: boolean, noTrack: boolean) {
		this.dryRun = dryRun
		this.force = force
		this.repoRoot = ''
		this.noTrack = noTrack
		this.projectId = ''
		this.overrideUnmanaged = new Set<string>()
	}

	log(message: string): void {
		console.log(`[wayforge] ${message}`)
	}
}

export type SyncTreeResult = {
	action: 'copied' | 'skipped' | 'error'
}

