import crypto from 'crypto'
import fs from 'fs-extra'
import path from 'path'
import {
	MANAGED_DIR_MARKER,
	MANAGED_OPENCODE_HEADER,
	type ManifestContext,
	type SyncTreeResult,
} from './context.js'
import { cp, ensureDir, rm, writeFile } from './files.js'

/** Read a file and split into lines, normalizing CRLF to LF. */
function readFileLines(filePath: string): string[] {
	return fs.readFileSync(filePath, 'utf8').replace(/\r/g, '').split('\n')
}

/** Normalize Windows backslashes to POSIX forward slashes. */
export function posixPath(p: string): string {
	return p.replace(/\\/g, '/')
}

/** Returns the path portion of a manifest list entry (`- path` or `  - path`), or null. */
function parseListEntry(line: string): string | null {
	if (line.startsWith('- ')) {
		return line.slice(2)
	}
	if (line.startsWith('  - ')) {
		return line.slice(4)
	}
	return null
}

/** Read the project_id field from an existing .ai-config-managed file. */
export function readManagedProjectId(repo: string): string | null {
	const manifest = path.join(repo, '.ai-config-managed')
	if (!fs.pathExistsSync(manifest)) {
		return null
	}

	const lines = readFileLines(manifest)
	for (const line of lines) {
		const match = line.match(/^project_id:\s*(.+)$/)
		if (match) {
			return match[1].trim()
		}
	}
	return null
}

export function initManagedManifest(
	repo: string,
	version: string,
	ref: string | undefined,
	ctx: ManifestContext,
): void {
	ctx.repoRoot = repo
	const manifestTmp = path.join(repo, '.ai-config-managed.tmp')

	if (ctx.dryRun) {
		ctx.log(`DRY-RUN: would initialize managed manifest at ${manifestTmp}`)
		return
	}

	// Read existing projectId if reinstalling; otherwise generate a new one.
	const existingId = readManagedProjectId(repo)
	if (existingId) {
		ctx.projectId = existingId
	} else {
		ctx.projectId = crypto.randomUUID()
	}

	const projectIdLine = `project_id: ${ctx.projectId}\n`
	const header = ref
		? `${projectIdLine}# Generated by ai-config v${version} (ref: ${ref})\nversion: ${version}\nref: ${ref}\nmanaged_paths:\n\n`
		: `${projectIdLine}# Generated by ai-config v${version}\nversion: ${version}\nmanaged_paths:\n\n`

	fs.writeFileSync(manifestTmp, header)
	ctx.log(`initialized managed manifest: ${manifestTmp}`)
}

export function addManagedPath(
	repo: string,
	relativePath: string,
	ctx: ManifestContext,
): void {
	const manifestTmp = path.join(repo, '.ai-config-managed.tmp')

	if (!fs.pathExistsSync(manifestTmp)) {
		return
	}

	if (ctx.dryRun) {
		ctx.log(`DRY-RUN: would add managed path: ${relativePath}`)
		return
	}

	const lines = readFileLines(manifestTmp)
	const entry = posixPath(relativePath)
	if (lines.includes(`- ${entry}`)) {
		return
	}

	fs.appendFileSync(manifestTmp, `- ${entry}\n`)
}

export function finalizeManagedManifest(
	repo: string,
	ctx: ManifestContext,
): void {
	const manifestTmp = path.join(repo, '.ai-config-managed.tmp')
	const manifestFinal = path.join(repo, '.ai-config-managed')

	if (!fs.pathExistsSync(manifestTmp)) {
		ctx.repoRoot = ''
		return
	}

	if (ctx.dryRun) {
		ctx.log(`DRY-RUN: would finalize managed manifest at ${manifestFinal}`)
		ctx.log(
			'DRY-RUN: would remove old per-file markers under managed paths',
		)
		ctx.repoRoot = ''
		return
	}

	fs.moveSync(manifestTmp, manifestFinal, { overwrite: true })
	ctx.log(`finalized managed manifest: ${manifestFinal}`)
	ctx.repoRoot = ''

	const content = fs.readFileSync(manifestFinal, 'utf8')
	const managedPaths = parseManagedPaths(content)

	for (const managedPath of managedPaths) {
		const sidecar = path.join(repo, `${managedPath}.ai-config-managed`)
		if (fs.pathExistsSync(sidecar)) {
			fs.unlinkSync(sidecar)
			ctx.log(`removed old sidecar marker: ${sidecar}`)
		}
	}

	for (const managedPath of managedPaths) {
		let dir = path.dirname(path.join(repo, managedPath))
		while (dir !== repo) {
			const dm = path.join(dir, MANAGED_DIR_MARKER)
			if (fs.pathExistsSync(dm) && dm !== manifestFinal) {
				fs.unlinkSync(dm)
				ctx.log(`removed old directory marker: ${dm}`)
			}
			const parent = path.dirname(dir)
			if (parent === dir) {
				break
			}
			dir = parent
		}
	}
}

export function readManagedManifest(repo: string): string[] {
	const manifest = path.join(repo, '.ai-config-managed')
	if (!fs.pathExistsSync(manifest)) {
		return []
	}

	const content = fs.readFileSync(manifest, 'utf8')
	return parseManagedPaths(content)
}

function parseManagedPaths(content: string): string[] {
	const paths: string[] = []
	let readingPaths = false

	for (const line of content.replace(/\r/g, '').split('\n')) {
		if (line === 'managed_paths:') {
			readingPaths = true
			continue
		}

		if (readingPaths) {
			const entry = parseListEntry(line)
			if (entry !== null) {
				paths.push(entry)
			} else if (line === '') {
				continue
			} else if (!line.startsWith(' ')) {
				readingPaths = false
			}
		}
	}

	return paths
}

export function isManagedPath(repo: string, relativePath: string): boolean {
	if (
		fs.pathExistsSync(path.join(repo, `${relativePath}.ai-config-managed`))
	) {
		return true
	}

	const manifest = path.join(repo, '.ai-config-managed')
	if (fs.pathExistsSync(manifest)) {
		const lines = readFileLines(manifest)
		const pp = posixPath(relativePath)
		return lines.some((line) => parseListEntry(line) === pp)
	}

	return false
}

export function isManagedFile(absolutePath: string): boolean {
	if (fs.pathExistsSync(`${absolutePath}.ai-config-managed`)) {
		return true
	}

	let dir = path.dirname(absolutePath)
	while (dir !== '/') {
		for (const name of ['.ai-config-managed', '.ai-config-managed.tmp']) {
			const manifest = path.join(dir, name)
			if (fs.pathExistsSync(manifest)) {
				const relPath = absolutePath.slice(dir.length + 1)
				if (relPath && relPath !== absolutePath) {
					const lines = readFileLines(manifest)
					const pp = posixPath(relPath)
					if (lines.some((line) => parseListEntry(line) === pp)) {
						return true
					}
				}
				break
			}
		}
		const parent = path.dirname(dir)
		if (parent === dir) {
			break
		}
		dir = parent
	}

	return false
}

export function isManagedDir(absolutePath: string): boolean {
	if (fs.pathExistsSync(path.join(absolutePath, MANAGED_DIR_MARKER))) {
		return true
	}

	let dir = absolutePath
	while (dir !== '/') {
		for (const name of ['.ai-config-managed', '.ai-config-managed.tmp']) {
			const manifest = path.join(dir, name)
			if (fs.pathExistsSync(manifest)) {
				const relPath = absolutePath.slice(dir.length + 1)
				if (relPath && relPath !== absolutePath) {
					const lines = readFileLines(manifest)
					const rp = posixPath(relPath)
					if (lines.some((line) => parseListEntry(line) === rp)) {
						return true
					}
					for (const line of lines) {
						const entry = parseListEntry(line)
						if (entry !== null && entry.startsWith(`${rp}/`)) {
							return true
						}
					}
				}
				break
			}
		}
		const parent = path.dirname(dir)
		if (parent === dir) {
			break
		}
		dir = parent
	}

	return false
}

export function isManagedOpenCodeFile(absolutePath: string): boolean {
	if (
		!fs.pathExistsSync(absolutePath) ||
		!fs.statSync(absolutePath).isFile()
	) {
		return false
	}

	const firstLine = fs
		.readFileSync(absolutePath, 'utf8')
		.split('\n')[0]
		.replace(/\r$/, '')
	return firstLine === MANAGED_OPENCODE_HEADER
}

export function managedTrackFile(dstFile: string, ctx: ManifestContext): void {
	if (
		ctx.repoRoot &&
		fs.pathExistsSync(path.join(ctx.repoRoot, '.ai-config-managed.tmp'))
	) {
		const rel = posixPath(dstFile.slice(ctx.repoRoot.length + 1))
		if (rel && rel !== dstFile) {
			addManagedPath(ctx.repoRoot, rel, ctx)
			return
		}
	}

	writeFile(
		`${dstFile}.ai-config-managed`,
		'generated-by=ai-config-bootstrap',
		ctx,
	)
}

export function syncManagedFile(
	src: string,
	dst: string,
	ctx: ManifestContext,
): void {
	if (!fs.pathExistsSync(src) || !fs.statSync(src).isFile()) {
		ctx.log(`error: source file does not exist: ${src}`)
		process.exit(1)
	}

	if (fs.pathExistsSync(dst) && fs.lstatSync(dst).isSymbolicLink()) {
		if (!ctx.force) {
			if (isManagedFile(dst)) {
				managedTrackFile(dst, ctx)
				ctx.log(
					`kept existing managed file (tracked in manifest): ${dst}`,
				)
				return
			}
			ctx.log(
				`keep existing file (use --force to refresh managed file): ${dst}`,
			)
			return
		}
		if (!isManagedFile(dst) && !ctx.overrideUnmanaged.has(dst)) {
			ctx.log(
				`skip conflict with unmanaged file (preserving local content): ${dst}`,
			)
			return
		}
		rm(dst, ctx)
	} else if (fs.pathExistsSync(dst)) {
		if (!ctx.force) {
			if (isManagedFile(dst)) {
				managedTrackFile(dst, ctx)
				ctx.log(
					`kept existing managed file (tracked in manifest): ${dst}`,
				)
				return
			}
			ctx.log(
				`keep existing file (use --force to refresh managed file): ${dst}`,
			)
			return
		}
		if (!isManagedFile(dst) && !ctx.overrideUnmanaged.has(dst)) {
			ctx.log(
				`skip conflict with unmanaged file (preserving local content): ${dst}`,
			)
			return
		}
		rm(dst, ctx)
	}

	ensureDir(path.dirname(dst), ctx)
	cp(src, dst, ctx)
	managedTrackFile(dst, ctx)

	if (ctx.dryRun) {
		ctx.log(`DRY-RUN: would copy managed file: ${dst}`)
	} else {
		ctx.log(`copied managed file: ${dst}`)
	}
}

export function syncManagedTree(
	srcDir: string,
	dstDir: string,
	ctx: ManifestContext,
): SyncTreeResult {
	if (!fs.pathExistsSync(srcDir) || !fs.statSync(srcDir).isDirectory()) {
		ctx.log(`error: source directory does not exist: ${srcDir}`)
		process.exit(1)
	}

	if (fs.pathExistsSync(dstDir) && fs.lstatSync(dstDir).isSymbolicLink()) {
		ctx.log(
			`skip conflict with existing symlink (preserving local content): ${dstDir} -> ${fs.readlinkSync(dstDir)}`,
		)
		return { action: 'skipped' }
	}

	if (fs.pathExistsSync(dstDir) && !fs.statSync(dstDir).isDirectory()) {
		ctx.log(
			`skip conflict with non-directory path (preserving local content): ${dstDir}`,
		)
		return { action: 'skipped' }
	}

	let dstTreeExisted = false
	let dstTreeWasManaged = false

	if (fs.pathExistsSync(dstDir) && fs.statSync(dstDir).isDirectory()) {
		dstTreeExisted = true
		if (isManagedDir(dstDir)) {
			dstTreeWasManaged = true
		}
	}

	ensureDir(dstDir, ctx)

	const manifestActive =
		ctx.repoRoot !== '' &&
		fs.pathExistsSync(path.join(ctx.repoRoot, '.ai-config-managed.tmp'))

	if (
		(!dstTreeExisted || dstTreeWasManaged) &&
		!fs.pathExistsSync(path.join(dstDir, MANAGED_DIR_MARKER)) &&
		!manifestActive
	) {
		writeFile(
			path.join(dstDir, MANAGED_DIR_MARKER),
			'generated-by=ai-config-bootstrap',
			ctx,
		)
		if (ctx.dryRun) {
			ctx.log(`DRY-RUN: would mark managed tree: ${dstDir}`)
		} else {
			ctx.log(`marked managed tree: ${dstDir}`)
		}
	}

	let action: SyncTreeResult['action'] = 'skipped'

	for (const srcFile of walkFiles(srcDir)) {
		const relPath = srcFile.slice(srcDir.length + 1)
		const dstFile = path.join(dstDir, relPath)
		const dstParent = path.dirname(dstFile)

		if (
			fs.pathExistsSync(dstParent) &&
			(fs.lstatSync(dstParent).isSymbolicLink() ||
				!fs.statSync(dstParent).isDirectory())
		) {
			ctx.log(
				`skip conflict with non-directory parent (preserving local content): ${dstParent}`,
			)
			continue
		}

		ensureDir(dstParent, ctx)

		if (
			fs.pathExistsSync(dstFile) &&
			fs.lstatSync(dstFile).isSymbolicLink()
		) {
			if (
				!isManagedFile(dstFile) &&
				!dstTreeWasManaged &&
				!ctx.overrideUnmanaged.has(dstFile)
			) {
				ctx.log(
					`skip conflict with unmanaged path (preserving local content): ${dstFile}`,
				)
				continue
			}
			rm(dstFile, ctx)
			cp(srcFile, dstFile, ctx)
			managedTrackFile(dstFile, ctx)
			action = 'copied'
			if (ctx.dryRun) {
				ctx.log(`DRY-RUN: would refresh managed file: ${dstFile}`)
			} else {
				ctx.log(`refreshed managed file: ${dstFile}`)
			}
			continue
		}

		if (fs.pathExistsSync(dstFile)) {
			if (fs.statSync(dstFile).isDirectory()) {
				ctx.log(
					`skip conflict with non-file path (preserving local content): ${dstFile}`,
				)
				continue
			}
			if (
				!isManagedFile(dstFile) &&
				!dstTreeWasManaged &&
				!ctx.overrideUnmanaged.has(dstFile)
			) {
				ctx.log(
					`skip conflict with unmanaged path (preserving local content): ${dstFile}`,
				)
				continue
			}
			cp(srcFile, dstFile, ctx)
			managedTrackFile(dstFile, ctx)
			action = 'copied'
			if (ctx.dryRun) {
				ctx.log(`DRY-RUN: would refresh managed file: ${dstFile}`)
			} else {
				ctx.log(`refreshed managed file: ${dstFile}`)
			}
			continue
		}

		cp(srcFile, dstFile, ctx)
		managedTrackFile(dstFile, ctx)
		action = 'copied'
		if (ctx.dryRun) {
			ctx.log(`DRY-RUN: would create managed file: ${dstFile}`)
		} else {
			ctx.log(`created managed file: ${dstFile}`)
		}
	}

	if (action === 'skipped') {
		ctx.log(`kept managed tree (no file changes): ${dstDir}`)
	}

	return { action }
}

export function walkFiles(dir: string): string[] {
	const files: string[] = []
	const entries = fs.readdirSync(dir, { withFileTypes: true })
	for (const entry of entries) {
		const fullPath = path.join(dir, entry.name)
		if (entry.isDirectory()) {
			files.push(...walkFiles(fullPath))
		} else if (entry.isFile()) {
			files.push(fullPath)
		}
	}
	return files
}

export function syncManagedPathFromManifest(
	repo: string,
	relativePath: string,
	rootDir: string,
	ctx: ManifestContext,
): void {
	let srcFile = ''

	if (relativePath === 'opencode.jsonc' || relativePath === 'kilo.jsonc') {
		return
	} else if (relativePath === 'AGENTS.md') {
		srcFile = path.join(rootDir, 'base', 'AGENTS.md')
	} else if (relativePath.startsWith('.opencode/agents/')) {
		const subpath = relativePath.slice('.opencode/agents/'.length)
		srcFile = path.join(rootDir, 'base', 'opencode', 'agents', subpath)
	} else if (relativePath.startsWith('.opencode/commands/')) {
		const subpath = relativePath.slice('.opencode/commands/'.length)
		srcFile = path.join(rootDir, 'base', 'opencode', 'commands', subpath)
	} else if (relativePath.startsWith('.opencode/skills/')) {
		const subpath = relativePath.slice('.opencode/skills/'.length)
		srcFile = path.join(rootDir, 'base', 'opencode', 'skills', subpath)
	} else if (relativePath.startsWith('.opencode/plugins/')) {
		const subpath = relativePath.slice('.opencode/plugins/'.length)
		srcFile = path.join(rootDir, 'base', 'opencode', 'plugins', subpath)
	} else {
		ctx.log(
			`warning: unknown managed path prefix, skipping: ${relativePath}`,
		)
		return
	}

	if (
		!srcFile ||
		(fs.pathExistsSync(srcFile) && fs.statSync(srcFile).isDirectory())
	) {
		return
	}

	if (!fs.pathExistsSync(srcFile)) {
		ctx.log(
			`warning: source not found for managed path '${relativePath}', skipping: ${srcFile}`,
		)
		return
	}

	syncManagedFile(srcFile, path.join(repo, relativePath), ctx)
}
