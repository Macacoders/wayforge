import { describe, it, expect, beforeEach, afterEach } from "vitest";
import fs from "fs-extra";
import os from "os";
import path from "path";
import { ManifestContext } from "../../src/lib/context.js";
import {
  initManagedManifest,
  addManagedPath,
  finalizeManagedManifest,
  readManagedManifest,
  isManagedPath,
  isManagedFile,
  isManagedDir,
  isManagedOpenCodeFile,
  syncManagedPathFromManifest,
} from "../../src/lib/manifest.js";

function makeCtx(dryRun = false): ManifestContext {
  return new ManifestContext(dryRun, false, false);
}

describe("manifest lifecycle", () => {
  let tmpDir: string;
  let repo: string;

  beforeEach(() => {
    tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "ai-config-test-"));
    repo = path.join(tmpDir, "repo");
    fs.mkdirpSync(repo);
  });

  afterEach(() => {
    fs.removeSync(tmpDir);
  });

  it("initManagedManifest creates tmp with correct header (no ref)", () => {
    const ctx = makeCtx();
    initManagedManifest(repo, "0.1.0", undefined, ctx);

    const manifestTmp = path.join(repo, ".ai-config-managed.tmp");
    expect(fs.pathExistsSync(manifestTmp)).toBe(true);
    const content = fs.readFileSync(manifestTmp, "utf8");
    expect(content).toMatch(/^project_id: [0-9a-f-]{36}\n/);
    expect(content).toContain("# Generated by ai-config v0.1.0");
    expect(content).toContain("version: 0.1.0");
    expect(content).toContain("managed_paths:");
    expect(ctx.repoRoot).toBe(repo);
    expect(ctx.projectId).toMatch(/^[0-9a-f-]{36}$/);
  });

  it("initManagedManifest creates tmp with ref", () => {
    const ctx = makeCtx();
    initManagedManifest(repo, "0.1.0", "v0.1.0", ctx);

    const manifestTmp = path.join(repo, ".ai-config-managed.tmp");
    expect(fs.pathExistsSync(manifestTmp)).toBe(true);
    const content = fs.readFileSync(manifestTmp, "utf8");
    expect(content).toMatch(/^project_id: [0-9a-f-]{36}\n/);
    expect(content).toContain("# Generated by ai-config v0.1.0 (ref: v0.1.0)");
    expect(content).toContain("version: 0.1.0");
    expect(content).toContain("ref: v0.1.0");
    expect(content).toContain("managed_paths:");
  });

  it("addManagedPath appends path", () => {
    const ctx = makeCtx();
    initManagedManifest(repo, "0.1.0", undefined, ctx);
    addManagedPath(repo, ".opencode/agents/planner.md", ctx);

    const content = fs.readFileSync(
      path.join(repo, ".ai-config-managed.tmp"),
      "utf8",
    );
    expect(content).toContain("  - .opencode/agents/planner.md");
  });

  it("addManagedPath deduplicates", () => {
    const ctx = makeCtx();
    initManagedManifest(repo, "0.1.0", undefined, ctx);
    addManagedPath(repo, "foo.md", ctx);
    addManagedPath(repo, "foo.md", ctx);

    const content = fs.readFileSync(
      path.join(repo, ".ai-config-managed.tmp"),
      "utf8",
    );
    const matches = content.split("\n").filter((line) => line === "  - foo.md");
    expect(matches.length).toBe(1);
  });

  it("finalizeManagedManifest moves tmp to final", () => {
    const ctx = makeCtx();
    initManagedManifest(repo, "0.1.0", undefined, ctx);
    addManagedPath(repo, "foo.md", ctx);
    addManagedPath(repo, "bar.md", ctx);
    finalizeManagedManifest(repo, ctx);

    expect(fs.pathExistsSync(path.join(repo, ".ai-config-managed.tmp"))).toBe(
      false,
    );
    expect(fs.pathExistsSync(path.join(repo, ".ai-config-managed"))).toBe(true);

    const content = fs.readFileSync(
      path.join(repo, ".ai-config-managed"),
      "utf8",
    );
    expect(content).toContain("  - foo.md");
    expect(content).toContain("  - bar.md");
    expect(ctx.repoRoot).toBe("");
  });

  it("finalizeManagedManifest cleans old sidecar markers", () => {
    fs.mkdirpSync(path.join(repo, "sub"));
    fs.writeFileSync(path.join(repo, "sub", "old.md"), "content");
    fs.writeFileSync(
      path.join(repo, "sub", "old.md.ai-config-managed"),
      "generated-by=ai-config-bootstrap",
    );

    const ctx = makeCtx();
    initManagedManifest(repo, "0.1.0", undefined, ctx);
    addManagedPath(repo, "sub/old.md", ctx);
    finalizeManagedManifest(repo, ctx);

    expect(
      fs.pathExistsSync(path.join(repo, "sub", "old.md.ai-config-managed")),
    ).toBe(false);
  });

  it("finalizeManagedManifest cleans old directory markers", () => {
    fs.mkdirpSync(path.join(repo, "sub"));
    fs.writeFileSync(
      path.join(repo, "sub", ".ai-config-managed"),
      "generated-by=ai-config-bootstrap",
    );

    const ctx = makeCtx();
    initManagedManifest(repo, "0.1.0", undefined, ctx);
    addManagedPath(repo, "sub/file.md", ctx);
    finalizeManagedManifest(repo, ctx);

    expect(fs.pathExistsSync(path.join(repo, "sub", ".ai-config-managed"))).toBe(
      false,
    );
  });

  it("readManagedManifest parses paths correctly", () => {
    const content = [
      "# Generated by ai-config v0.1.0",
      "version: 0.1.0",
      "managed_paths:",
      "  - foo.md",
      "  - .opencode/agents/planner.md",
      "  - .opencode/skills/create.md",
      "",
    ].join("\n");
    fs.writeFileSync(path.join(repo, ".ai-config-managed"), content);

    const paths = readManagedManifest(repo);
    expect(paths).toEqual([
      "foo.md",
      ".opencode/agents/planner.md",
      ".opencode/skills/create.md",
    ]);
  });

  it("readManagedManifest returns empty if no manifest", () => {
    expect(readManagedManifest(repo)).toEqual([]);
  });
});

describe("managed detection", () => {
  let tmpDir: string;
  let repo: string;

  beforeEach(() => {
    tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "ai-config-test-"));
    repo = path.join(tmpDir, "repo");
    fs.mkdirpSync(repo);
  });

  afterEach(() => {
    fs.removeSync(tmpDir);
  });

  it("isManagedPath detects sidecar marker", () => {
    fs.writeFileSync(path.join(repo, "foo.md"), "content");
    fs.writeFileSync(
      path.join(repo, "foo.md.ai-config-managed"),
      "generated-by=ai-config-bootstrap",
    );
    expect(isManagedPath(repo, "foo.md")).toBe(true);
  });

  it("isManagedPath detects unified manifest entry", () => {
    fs.writeFileSync(
      path.join(repo, ".ai-config-managed"),
      "managed_paths:\n  - bar.md\n",
    );
    expect(isManagedPath(repo, "bar.md")).toBe(true);
  });

  it("isManagedPath returns false for untracked path", () => {
    expect(isManagedPath(repo, "baz.md")).toBe(false);
  });

  it("isManagedFile detects sidecar", () => {
    fs.mkdirpSync(path.join(repo, "sub"));
    fs.writeFileSync(path.join(repo, "sub", "file.txt"), "content");
    fs.writeFileSync(
      path.join(repo, "sub", "file.txt.ai-config-managed"),
      "generated-by=ai-config-bootstrap",
    );
    expect(isManagedFile(path.join(repo, "sub", "file.txt"))).toBe(true);
  });

  it("isManagedFile walks directory tree", () => {
    fs.mkdirpSync(path.join(repo, ".opencode", "agents"));
    fs.writeFileSync(path.join(repo, ".opencode", "agents", "planner.md"), "");
    fs.writeFileSync(
      path.join(repo, ".ai-config-managed"),
      "managed_paths:\n  - .opencode/agents/planner.md\n",
    );
    expect(
      isManagedFile(path.join(repo, ".opencode", "agents", "planner.md")),
    ).toBe(true);
  });

  it("isManagedDir detects per-dir marker", () => {
    fs.mkdirpSync(path.join(repo, "sub"));
    fs.writeFileSync(
      path.join(repo, "sub", ".ai-config-managed"),
      "generated-by=ai-config-bootstrap",
    );
    expect(isManagedDir(path.join(repo, "sub"))).toBe(true);
  });

  it("isManagedDir detects via manifest entry", () => {
    fs.mkdirpSync(path.join(repo, ".opencode", "agents"));
    fs.writeFileSync(
      path.join(repo, ".ai-config-managed"),
      "managed_paths:\n  - .opencode/agents\n",
    );
    expect(isManagedDir(path.join(repo, ".opencode", "agents"))).toBe(true);
  });

  it("isManagedDir detects child via manifest prefix", () => {
    fs.mkdirpSync(path.join(repo, ".opencode", "agents"));
    fs.writeFileSync(
      path.join(repo, ".ai-config-managed"),
      "managed_paths:\n  - .opencode/agents/planner.md\n",
    );
    expect(isManagedDir(path.join(repo, ".opencode", "agents"))).toBe(true);
  });

  it("isManagedOpenCodeFile matches header", () => {
    const file = path.join(repo, "managed.md");
    fs.writeFileSync(file, "// Generated by ai-config bootstrap\ncontent");
    expect(isManagedOpenCodeFile(file)).toBe(true);
  });

  it("isManagedOpenCodeFile returns false for non-managed file", () => {
    const file = path.join(repo, "other.md");
    fs.writeFileSync(file, "# Heading\ncontent");
    expect(isManagedOpenCodeFile(file)).toBe(false);
  });
});

describe("syncManagedPathFromManifest", () => {
  let tmpDir: string;
  let repo: string;
  let rootDir: string;

  beforeEach(() => {
    tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), "ai-config-test-"));
    repo = path.join(tmpDir, "repo");
    rootDir = path.join(tmpDir, "root");
    fs.mkdirpSync(repo);
    fs.mkdirpSync(path.join(rootDir, "base"));
  });

  afterEach(() => {
    fs.removeSync(tmpDir);
  });

  it("skips opencode.jsonc", () => {
    const ctx = makeCtx();
    syncManagedPathFromManifest(repo, "opencode.jsonc", rootDir, ctx);
    expect(fs.readdirSync(repo).length).toBe(0);
  });

  it("logs warning for unknown prefix", () => {
    const ctx = makeCtx();
    syncManagedPathFromManifest(repo, "unknown/path.txt", rootDir, ctx);
    expect(fs.readdirSync(repo).length).toBe(0);
  });

  it("maps AGENTS.md prefix", () => {
    fs.writeFileSync(path.join(rootDir, "base", "AGENTS.md"), "# Agents\n");

    const ctx = makeCtx();
    syncManagedPathFromManifest(repo, "AGENTS.md", rootDir, ctx);

    expect(fs.readFileSync(path.join(repo, "AGENTS.md"), "utf8")).toBe(
      "# Agents\n",
    );
  });
});
