import fs from 'fs-extra'
import path from 'path'
import { expect, vi } from 'vitest'
import { MANAGED_OPENCODE_HEADER } from '../../src/lib/context.js'
import { canSymlink } from '../../src/lib/pointers.js'
import type { InstallOptions, Runtime } from '../../src/types.js'

/** Repository root that provides the `base/` source tree for installs. */
export const sourceDir = path.resolve(__dirname, '../../..')

/** True when this host can create directory symlinks (ADR-0031 probe). */
export const symlinks = canSymlink()

export function installOptions(
	repo: string,
	runtime: Runtime,
	overrides: Partial<InstallOptions> = {},
): InstallOptions {
	return {
		repo,
		providers: 'openai',
		runtime,
		dryRun: false,
		force: false,
		skipNodeCheck: true,
		noTrack: true,
		...overrides,
	}
}

export function configFileFor(runtime: Runtime): string {
	return runtime === 'opencode' ? 'opencode.jsonc' : 'kilo.jsonc'
}

export function pointerRootFor(runtime: Runtime): string {
	return runtime === 'opencode' ? '.opencode' : '.kilo'
}

/** Seed a legacy install: managed files plus a v0.1.0 `.opencode` manifest. */
export function seedLegacyInstall(
	repo: string,
	managedPaths: string[],
): void {
	for (const relPath of managedPaths) {
		const absolute = path.join(repo, relPath)
		fs.mkdirpSync(path.dirname(absolute))
		fs.writeFileSync(absolute, `# legacy ${path.basename(relPath)}\n`)
	}
	fs.writeFileSync(
		path.join(repo, '.wayforge-managed'),
		[
			'project_id: legacy-project',
			'# Generated by wayforge v0.1.0',
			'version: 0.1.0',
			'managed_paths:',
			'',
			...managedPaths.map((relPath) => `- ${relPath}`),
			'',
		].join('\n'),
	)
}

/** Seed the config a legacy install generated: `.opencode` plugin, no skills. */
export function seedLegacyConfig(
	repo: string,
	runtime: Runtime = 'opencode',
): string {
	const configPath = path.join(repo, configFileFor(runtime))
	fs.writeFileSync(
		configPath,
		[
			MANAGED_OPENCODE_HEADER,
			'{',
			'  "plugin": ["./.opencode/plugins/ponytail/ponytail.mjs"]',
			'}',
			'',
		].join('\n'),
	)
	return configPath
}

export function readAgentContents(repo: string): Record<string, string> {
	const agentsDir = path.join(repo, '.agents', 'agents')
	const contents: Record<string, string> = {}
	for (const name of fs.readdirSync(agentsDir)) {
		if (!name.endsWith('.md')) continue
		contents[name] = fs.readFileSync(path.join(agentsDir, name), 'utf8')
	}
	return contents
}

export function captureLogs(): string[] {
	const logs: string[] = []
	vi.spyOn(console, 'log').mockImplementation((...args: unknown[]) => {
		logs.push(args.map((arg) => String(arg)).join(' '))
	})
	return logs
}

export function mockExit(): void {
	vi.spyOn(process, 'exit').mockImplementation(((code?: number) => {
		throw new Error(`process.exit:${String(code)}`)
	}) as never)
}

export function expectPointer(
	repo: string,
	pointerRel: string,
	targetRel: string,
): void {
	const link = path.join(repo, pointerRel)
	const target = path.join(repo, targetRel)

	expect(fs.pathExistsSync(link)).toBe(true)
	expect(fs.statSync(link).isDirectory()).toBe(true)
	if (symlinks) {
		expect(fs.lstatSync(link).isSymbolicLink()).toBe(true)
		expect(path.resolve(path.dirname(link), fs.readlinkSync(link))).toBe(
			path.resolve(target),
		)
	}
}
